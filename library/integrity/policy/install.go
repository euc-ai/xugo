// Package policy holds the canonical per-target proof-policy table:
// for each target that uses or is denied a capability, what its
// recorded proof used and what the complete dependency graph
// denies it.
//
// The table is corpus content — one entry per proved target, growing
// without bound as theorems land — which is why it lives here and not
// in prover/. Its consumer (proof.NewProofScope, and the engine's
// emit/curate scope checks) is fixed machinery inside the tent, and the
// tent never imports library/, so the table is INSTALLED at startup
// rather than imported: the same inversion the omega bundles use.
//
// policy_gen.go is generated by library/cmd/policy_gen from
// manifest.Build's complete graph; regenerate it after the proof graph
// changes. manifest_test pins Digest against a freshly built graph, so
// a stale table is a loud test failure, not a silent wrong answer.
package policy

import "github.com/euc-ai/xugo/prover/proof"

// Install hands the generated table to the tent-side query API. Called
// at startup by serve.InstallProofPolicy; idempotent.
//
// Leaving it uninstalled is legitimate — library/cmd/policy_gen runs
// proofs in order to COMPUTE the table and necessarily starts with
// none — but then NewProofScope cannot apply the complete graph's
// indirect-cycle verdicts. Harnesses that rely on them assert
// proof.ProofPolicyInstalled().
func Install() { proof.InstallProofPolicy(policies, Digest) }
