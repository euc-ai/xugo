// Package vocabgen renders a family's VocabSpec into the chapter's
// programmable-term surface — the zz_vocab_gen.go the gen_family
// command writes and the drift gate re-renders. It is a separate
// package so the command and the gate share one renderer: what the
// gate compares against disk is byte-for-byte what the command would
// write.
//
// The rendered surface is deliberately thin: an ops struct with one
// *ext.TermWrapper field per handle row, an `ops` constructor whose every
// assignment routes through the spec (`vocab.Handle(ctx, …)` — the
// package-level spec variable, the naming convention WithVocabSpec
// documents), and build-site methods for the nullary rows. Types are
// never spelled here — they live in the domain alphabet and the
// Spelled rows, read at runtime — so the generated file cannot drift
// from the declaration in MEANING; the drift gate guards the remaining
// surface-level staleness (a row added without regeneration).
//
// The file names the proof surface qualified (*proof.Script,
// *ext.TermWrapper) and does not import library/authoring, whose names
// belong to the proof files that dot-import it.
package vocabgen

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/euc-ai/xugo/library/registry"
)

// Render produces the zz_vocab_gen.go content for fam's VocabSpec in
// the given Go package, or nil when the family has no spec or the spec
// yields no generated surface (a declare-only chapter needs no file).
func Render(fam *registry.Family, pkgName string) ([]byte, error) {
	spec := fam.VocabSpec()
	if spec == nil {
		return nil, nil
	}
	rows := spec.RowInfos()

	var fields, polys, embeds []registry.VocabRowInfo
	for _, r := range rows {
		switch r.Kind {
		case "term", "spelled", "defined", "text", "built":
			fields = append(fields, r)
		case "poly":
			polys = append(polys, r)
		case "embed":
			embeds = append(embeds, r)
		}
	}
	if len(fields) == 0 && len(polys) == 0 && len(embeds) == 0 {
		return nil, nil
	}

	opsType := spec.OpsTypeName()
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen_family; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// The chapter vocabulary as programmable terms, rendered from the\n")
	fmt.Fprintf(&b, "// VocabSpec rows in vocab.go — one handle per declared name. The\n")
	fmt.Fprintf(&b, "// family installs the declarations (VocabSpec.Install); a member\n")
	fmt.Fprintf(&b, "// builds the handles in one line, `v := ops(a.Ctx())`.\n")
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)

	// The import block: the script every ops constructor takes, the
	// handle type where a row yields one, the element type where a
	// polymorphic row is read at one, and the bundles embedded.
	imports := map[string]string{"github.com/euc-ai/xugo/prover/proof": ""}
	if len(fields) > 0 || len(polys) > 0 {
		imports["github.com/euc-ai/xugo/ext"] = ""
	}
	if len(polys) > 0 && spec.ElemVar() != "" {
		imports["github.com/euc-ai/xugo/core"] = ""
	}
	for _, e := range embeds {
		imports[e.Bundle.Path] = e.Bundle.Pkg + " "
	}
	paths := make([]string, 0, len(imports))
	for p := range imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	fmt.Fprintf(&b, "import (\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s%q\n", imports[p], p)
	}
	fmt.Fprintf(&b, ")\n\n")

	fmt.Fprintf(&b, "// %s is the chapter vocabulary's build surface.\n", opsType)
	fmt.Fprintf(&b, "type %s struct {\n", opsType)
	if len(polys) > 0 {
		fmt.Fprintf(&b, "\tctx *proof.Script\n\n")
	}
	for _, e := range embeds {
		fmt.Fprintf(&b, "\t%s.%s\n", e.Bundle.Pkg, e.Bundle.Type)
	}
	if len(embeds) > 0 && len(fields) > 0 {
		fmt.Fprintf(&b, "\n")
	}
	for _, r := range fields {
		fmt.Fprintf(&b, "\t%s *ext.TermWrapper // %s\n", r.Field, fieldDoc(r))
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// ops builds the chapter's handles for a member body. Handle routes\n")
	fmt.Fprintf(&b, "// through the spec's own rows; Script.Const is idempotent, so building\n")
	fmt.Fprintf(&b, "// after the family's Install is free.\n")
	fmt.Fprintf(&b, "func ops(ctx *proof.Script) *%s {\n", opsType)
	fmt.Fprintf(&b, "\treturn &%s{\n", opsType)
	if len(polys) > 0 {
		fmt.Fprintf(&b, "\t\tctx: ctx,\n")
	}
	for _, e := range embeds {
		fmt.Fprintf(&b, "\t\t%s: %s.%s(ctx),\n", e.Bundle.Type, e.Bundle.Pkg, e.Bundle.New)
	}
	for _, r := range fields {
		fmt.Fprintf(&b, "\t\t%s: vocab.Handle(ctx, %q),\n", r.Field, r.Field)
	}
	fmt.Fprintf(&b, "\t}\n}\n")

	for _, r := range polys {
		fmt.Fprintf(&b, "\n// %s is the %s handle, pinned at the build site at the domain's\n", r.Field, r.Name)
		fmt.Fprintf(&b, "// generic instance — registry.Alphabet.Pinned through the spec.\n")
		fmt.Fprintf(&b, "func (v *%s) %s() *ext.TermWrapper { return vocab.PinnedHandle(v.ctx, %q) }\n",
			opsType, r.Field, r.Field)
		if spec.ElemVar() != "" {
			fmt.Fprintf(&b, "\n// %sAt is %s at a chosen element type — registry.Alphabet.PinnedAt.\n", r.Field, r.Field)
			fmt.Fprintf(&b, "func (v *%s) %sAt(elem core.HolType) *ext.TermWrapper {\n", opsType, r.Field)
			fmt.Fprintf(&b, "\treturn vocab.PinnedHandleAt(v.ctx, %q, elem)\n}\n", r.Field)
		}
	}

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("vocabgen: rendered source does not format (generator bug): %w", err)
	}
	return out, nil
}

// fieldDoc is the field's one-line provenance comment: the constant's
// name, or the build text for a text row.
func fieldDoc(r registry.VocabRowInfo) string {
	switch r.Kind {
	case "text":
		return "built: " + r.Text
	case "built":
		return "hand-built (vocab.go)"
	}
	return r.Name
}
