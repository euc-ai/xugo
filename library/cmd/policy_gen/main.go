// Command policy_gen generates the canonical per-target proof
// policy table (library/integrity/policy/policy_gen.go): per target, the
// capabilities its recorded proof used and the capabilities the
// complete dependency graph denies it. The table is the runtime lookup
// consumed by proof.NewProofScope so replay subprocesses don't rebuild
// the full manifest.Build graph on every start.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/euc-ai/xugo/library/integrity/manifest"
)

var policyOutput = flag.String("policy-output", "library/integrity/policy/policy_gen.go", "generated canonical proof-policy file")

func main() {
	flag.Parse()
	g, err := manifest.Build()
	check(err)
	check(writeCanonicalPolicies(g, *policyOutput))
}

func writeCanonicalPolicies(g *manifest.Graph, outputPath string) error {
	all := manifest.CanonicalProofPolicies(g)
	var b strings.Builder
	b.WriteString("// Code generated by library/cmd/policy_gen. DO NOT EDIT.\n\n")
	b.WriteString("package policy\n\n")
	b.WriteString("import (\n\t\"github.com/euc-ai/xugo/core\"\n\t\"github.com/euc-ai/xugo/prover/proof\"\n)\n\n")
	b.WriteString("var policies = map[core.PropKey]proof.Policy{\n")
	for _, policy := range all {
		// The name on its own line: a trailing comment would have gofmt
		// pad every row of the block to the longest one.
		fmt.Fprintf(&b, "\t// %s\n\t%q: {Used: %#v, Denied: %#v},\n", policy.Name, policy.Target, policy.Used, policy.Denied)
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "\nconst Digest = %q\n", manifest.PolicyDigest(g))
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(outputPath, src, 0o644)
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
