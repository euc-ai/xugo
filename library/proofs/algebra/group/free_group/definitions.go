// definitions.go — the chapter's definitional layer: letters, words
// and their inverses, the equivalence of words, the free group as the
// quotient by it, and the two elements every word is built from.
//
// A LETTER is a generator with a sign — a pair `(a, b)` of an element
// of the alphabet A and a boolean, `(a, ⊤)` the generator a and
// `(a, ⊥)` its inverse — and a WORD is a list of letters. Two words are
// EQUIVALENT when one is obtained from the other by inserting and
// deleting adjacent pairs `x, x⁻¹`: the relation is defined by its
// four rules — reflexivity, symmetry, transitivity, and the one
// cancellation — so that it is an equivalence by its first three rules
// and is generated by the fourth. The free group over A is the
// quotient of the words by this relation, whose class map
// `free_group_of_word` — written ⁅w⁆, the class of the word w — takes a
// word to its class. The quotient door mints the type over the class
// shape (mk_free_group / dest_free_group the bijection underneath) and
// gives the seven facts a quotient comes with; inhabitation is
// immediate, so the type costs the chapter no theorem beyond
// WordEquivEquivalence.
//
// The group's operations are defined AT CLASSES, by what they do to
// representatives: the product of the classes of u and v is the class
// of the concatenation u ++ v, and the inverse of the class of u is the
// class of u read backwards with every letter inverted. That such a
// rule defines a function is the respectfulness the lift door asks
// for, and the chapter's two congruence laws are exactly that
// obligation; the two lifts therefore live beside the laws they cite,
// after the congruences. The identity and the generators need no
// respectfulness — each is one class.

