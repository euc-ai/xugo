// wordInverseDef — the inverse of a word: every letter inverted, in
// reverse order.
var wordInverseDef = wordInverseDefThm{family.Define(registry.DefEntry{
	Name:  "wordInverseDef",
	Key:   "prop_8857b9443b690d50",
	Const: "word_inverse",
	Type:  "list(prod(A, bool)) → list(prod(A, bool))",
	Equations: []string{
		"∀w:list(prod(A, bool)). word_inverse(w) = list_reverse(list_map(letter_inverse, w))",
	},
	Deps: []registry.EntryLike{letterInverseDef},
})}

// wordEquiv — the equivalence of words: the smallest relation that is
// reflexive, symmetric and transitive and identifies a word with the
// word obtained by deleting an adjacent pair of a letter and its
// inverse anywhere in it. The theorems those four rules come with are
// the faces below.
var wordEquiv = family.DefineInductive(registry.InductiveEntry{
	Name: "wordEquiv",
	Keys: registry.InductiveKeys{
		Rules:        "prop_1daa49e8cba93035",
		Induct:       "prop_e644dd0ec89d98a5",
		Cases:        "prop_6ff9c38c9b033387",
		InductStrong: "prop_6ff46032f6b1d345",
	},
	Const: "word_equiv",
	Type:  "list(prod(A, bool)) → list(prod(A, bool)) → bool",
	Rules: []string{
		"∀w:list(prod(A, bool)). word_equiv(w, w)",
		"∀u v:list(prod(A, bool)). word_equiv(u, v) ⇒ word_equiv(v, u)",
		"∀u v w:list(prod(A, bool)). word_equiv(u, v) ∧ word_equiv(v, w) ⇒ word_equiv(u, w)",
		"∀u v:list(prod(A, bool)). ∀x:prod(A, bool). word_equiv(list_append(u, " +
			"cons(x, cons(letter_inverse(x), v))), list_append(u, v))",
	},
	Deps: []registry.EntryLike{letterInverseDef, list.ListAppendDef},
})

// wordEquivRules — a word is equivalent to itself, equivalence runs
// both ways and composes, and a word with an adjacent pair `x, x⁻¹`
// deleted is equivalent to the word: the definition's rule set,
// registered verbatim as its Rules theorem.
var wordEquivRules = wordEquivRulesThm{wordEquiv.Rules}

// wordEquivInduct — rule induction along the equivalence: a property
// of pairs of words that holds of every pair the four rules produce
// holds of every equivalent pair.
var wordEquivInduct = wordEquivInductThm{wordEquiv.Induct}

// wordEquivInductStrong — the same induction with each rule telling
// the proof that the pairs it builds on are themselves equivalent.
var wordEquivInductStrong = wordEquivInductStrongThm{wordEquiv.InductStrong}

// wordEquivCases — an equivalent pair came from one of the four rules.
var wordEquivCases = wordEquivCasesThm{wordEquiv.Cases}

// WordEquivEquivalence — the relation's first three rules, assembled:
// the equivalence of words is an equivalence, which is what the
// quotient door asks before it takes the classes.
var WordEquivEquivalence = wordEquivEquivalenceThm{family.Add(registry.ProofEntry{
	Name: "WordEquivEquivalence",
	Key:  "prop_301a45732a20e0a6",
	Build: family.Instance(equivalence.Equivalence, "equivalence(word_equiv)",
		Case(
			"reflexive: every word is equivalent to itself, the first rule",
			Unfold(equivalence.ReflexiveDef),
			By(Normalized, wordEquivRules)),
		Case(
			"symmetric: an equivalence runs the other way, the second rule",
			Unfold(equivalence.SymmetricDef),
			By(wordEquivRules)),
		Case(
			"transitive: two equivalences through a common word make one, the third rule",
			Unfold(equivalence.TransitiveDef),
			By(wordEquivRules))),
})}

// FreeGroupDef — the free group over A: the word_equiv-classes, made a
// type, with `free_group_of_word` the class map (⁅w⁆) and
// mk_free_group / dest_free_group the bijection underneath. Its seven
// facts (FreeGroupDef.Surjectivity, .Induct, .Sound, .Exact, .Eq,
// .ForallOnImage, .ExistsOnImage) are the chapter's whole bridge: a
// law over the free group inducts to words, the operations compute at
// classes, and Eq reads class equality as word_equiv.
var FreeGroupDef = family.DefineQuotient(registry.QuotientEntry{
	Name:        "FreeGroup",
	Type:        "free_group",
	Mk:          "free_group_of_word",
	Abs:         "mk_free_group",
	Rep:         "dest_free_group",
	Relation:    "word_equiv",
	Equivalence: WordEquivEquivalence,
	Deps:        []registry.EntryLike{wordEquivRules},
})

