// conormal.go — the conormal module of a ring map f from R onto S: with
// I the kernel of f, D_0(S/R, N) vanishes for every module N over S, and
// D_1(S/R, S) is I/I² as a module over S, for every quotient ring at
// once. The isomorphism is the conormal map, x in I going to the class
// of the differential of the 1-simplex var(x) − var(0) of the standard
// resolution; it is read off the standard resolution up to degree 2,
// where a retraction to R, giving each name of an element of S a
// preimage, inverts it modulo I². The quotient of a ring by an ideal is
// such an S; at a local ring and its non-units D_1 is the Zariski
// cotangent space m/m², and at a principal ideal generated by a
// non-zero-divisor g it is R/(g), so D_1(𝔽_p/ℤ, 𝔽_p) is 𝔽_p.

