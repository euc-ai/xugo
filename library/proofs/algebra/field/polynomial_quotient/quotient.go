// PolynomialPrincipalIdealDivides — a sequence lies in the ideal generated
// by a polynomial p exactly when p divides it: the ideal is the set of
// polynomial multiples of p, and a multiplier commutes with p.
var PolynomialPrincipalIdealDivides = polynomialPrincipalIdealDividesThm{family.Add(registry.ProofEntry{
	Name: "PolynomialPrincipalIdealDivides",
	Key:  "prop_c7676778c1543a2d",
	Build: family.Theorem(Statement{
		Binders: "∀F:field_on(A). ∀p r:(num → A).",
		Hypotheses: []string{
			"polynomial_over(F.carrier, p)",
		},
		Conclusion: "r ∈ «idealOfP» ⇔ polynomial_divides(field_ring(F), p, r)",
	}, func(a *Argument, F field.FieldFact[on.F], p, r *Expr[Fun[Nat, A]], over Fact) {
		polynomials := polynomial.PolynomialRingOn.Read(field.RingOn.Read(F))
		multiples := a.Have(
			"the ideal generated by p is the set of multiples of p",
			"r ∈ «idealOfP» ⇔ ∃s:(num → A). polynomial_over(F.carrier, s) ∧ r = polynomial_mul(s, p)",
			BySets(over, ring_ideal.PrincipalIdealMultiples.Read(polynomials).AsFact().At(p)))
		commute := a.Have(
			"a polynomial multiplier commutes with p",
			"∀s:(num → A). polynomial_over(F.carrier, s) ⇒ polynomial_mul(s, p) = polynomial_mul(p, s)",
			By(over, comm_monoid.CommOn.Read(comm_ring.MulMonoidOn.Read(polynomials))))
		a.Show(
			"divisibility by p is the same statement about multiples",
			Simp(Fwd(polynomial_division.PolynomialDividesDef)),
			By(multiples, commute))
	}),
})}

// PolynomialQuotientRemainder — modulo a nonzero polynomial p over a field,
// the class of a polynomial r has exactly one representative vanishing from
// the degree of p on: dividing r by p leaves such a remainder u in the class,
// and a second one v puts r in the form p w + v, a second division of r by p,
// so v is u.
var PolynomialQuotientRemainder = polynomialQuotientRemainderThm{family.Add(registry.ProofEntry{
	Name: "PolynomialQuotientRemainder",
	Key:  "prop_657cfd0651637613",
	Reading: "p ≠ 0 is load-bearing: modulo zero the quotient is the whole ring, each class one " +
		"polynomial, and only the zero polynomial vanishes from degree 0 on. Positive degree is not " +
		"needed: a nonzero constant p is a unit, the quotient has one class, and u is the zero polynomial.",
	Build: family.Theorem(Statement{
		Binders: "∀F:field_on(A). ∀p r:(num → A).",
		Hypotheses: []string{
			"polynomial_over(F.carrier, p)",
			"¬(p = vec_zero)",
			"polynomial_over(F.carrier, r)",
		},
		Conclusion: "∃u:(num → A). " +
			"    polynomial_over(F.carrier, u) ∧ " +
			"    vec⟨polynomial_degree(p)⟩(u) ∧ " +
			"    ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», r) = " +
			"    ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», u) ∧ " +
			"    (∀v:(num → A). " +
			"        polynomial_over(F.carrier, v) ∧ " +
			"        vec⟨polynomial_degree(p)⟩(v) ∧ " +
			"        ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», r) = " +
			"        ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», v) ⇒ " +
			"        v = u)",
		Abbrev: Abbrev{
			{Name: "polynomialsOverF", Text: "{h:(num → A) | polynomial_over(F.carrier, h)}"},
		},
	}, func(
		a *Argument,
		F field.FieldFact[on.F],
		p, r *Expr[Fun[Nat, A]],
		pOver, pNonzero, rOver Fact,
	) {
		fieldF := a.TermAs[FieldOps[A]]("F")
		coefficients := a.TermAs[RingOps[A]]("field_ring(F)")
		polynomialRing := a.TermAs[RingOps[Fun[Nat, A]]]("«fieldPolynomialRing»")
		ideal := a.TermAs[Set[Fun[Nat, A]]]("«idealOfP»")
		polynomials := polynomial.PolynomialRingOn.Read(field.RingOn.Read(F))
		isIdeal := a.Have(
			"the principal span is an ideal",
			"ring_ideal(«fieldPolynomialRing», «idealOfP»)",
			BySets(pOver, ring_ideal.SpanIdeal.Read(polynomials).At(a.TermAs[Set[Fun[Nat, A]]]("{p}"))))
		sameClass := a.Have(
			"two polynomials share a class exactly when p divides their difference",
			Statement{
				Binders: "∀g h:(num → A).",
				Hypotheses: []string{
					"polynomial_over(F.carrier, g)",
					"polynomial_over(F.carrier, h)",
				},
				Conclusion: "ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», g) = " +
					"ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», h) ⇔ " +
					"polynomial_divides(field_ring(F), p, vec_sub(g, h))",
			},
			Derive(func(b *Argument) {
				g := b.FixAs[Fun[Nat, A]]("g")
				h := b.FixAs[Fun[Nat, A]]("h")
				given := b.Assume()
				b.Show(
					"the cosets agree when the difference lies in the ideal of p, whose points are the multiples of p",
					By(
						isIdeal,
						pOver,
						given,
						quotient_ring.CosetEqIff.Read(polynomials).AsFact().At(ideal, g, h),
						quotient_ring.IdealQuotientProjectionDef.At(polynomialRing, ideal, g),
						quotient_ring.IdealQuotientProjectionDef.At(polynomialRing, ideal, h),
						PolynomialPrincipalIdealDivides.At(
							fieldF,
							p,
							b.TermAs[Fun[Nat, A]]("vec_sub(g, h)"))))
			}))
		q, u, division := a.Obtain2As[Fun[Nat, A], Fun[Nat, A]](
			"divide r by p",
			"∃q u:(num → A). «division»(F.carrier, r, p, q, u)",
			By(rOver, pOver, pNonzero, polynomial_division.DivisionExists.Read(F).At(r, p)))
		parts := a.Conjuncts(
			division,
			"the quotient q is a polynomial",
			"the remainder u is a polynomial",
			"u vanishes from the degree of p on",
			"r = p q + u")
		qOver, uOver, uShort, divided := parts[0], parts[1], parts[2], parts[3]
		divisionMembers := a.Have(
			"r, p, q and u lie in the ring of polynomials",
			"r ∈ «polynomialsOverF» ∧ p ∈ «polynomialsOverF» ∧ q ∈ «polynomialsOverF» ∧ u ∈ «polynomialsOverF»",
			By(rOver, pOver, qOver, uOver))
		difference := a.Have(
			"r − u is the multiple of p by q",
			"vec_sub(r, u) = polynomial_mul(p, q)",
			ByArith(polynomials, divisionMembers, divided))
		classOfU := a.Have(
			"the remainder shares the class of r",
			"ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», r) = "+
				"ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», u)",
			By(
				rOver,
				uOver,
				qOver,
				difference,
				sameClass.At(r, u),
				polynomial_division.PolynomialDividesDef.At(
					coefficients,
					p,
					a.TermAs[Fun[Nat, A]]("vec_sub(r, u)"))))
		unique := a.Have(
			"a short polynomial in the class of r is a second remainder of r, hence u",
			Statement{
				Binders: "∀v:(num → A).",
				Hypotheses: []string{
					"polynomial_over(F.carrier, v)",
					"vec⟨polynomial_degree(p)⟩(v)",
					"ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», r) = " +
						"ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», v)",
				},
				Conclusion: "v = u",
			},
			Derive(func(b *Argument) {
				v := b.FixAs[Fun[Nat, A]]("v")
				given := b.Assume()
				w, multiple := b.ObtainAs[Fun[Nat, A]](
					"sharing a class with r, v differs from it by a multiple of p",
					"∃w:(num → A). polynomial_over(F.carrier, w) ∧ vec_sub(r, v) = polynomial_mul(p, w)",
					By(
						rOver,
						given,
						sameClass.At(r, v),
						polynomial_division.PolynomialDividesDef.At(
							coefficients,
							p,
							b.TermAs[Fun[Nat, A]]("vec_sub(r, v)"))))
				members := b.Have(
					"r, v, p and w lie in the ring of polynomials",
					"r ∈ «polynomialsOverF» ∧ v ∈ «polynomialsOverF» ∧ p ∈ «polynomialsOverF» ∧ w ∈ «polynomialsOverF»",
					By(rOver, given, pOver, multiple))
				dividedToV := b.Have(
					"r divided by p leaves v with quotient w",
					"r = polynomial_mul(p, w) + v",
					ByArith(polynomials, members, multiple))
				b.Show(
					"division has one remainder",
					By(
						pOver,
						pNonzero,
						given,
						multiple,
						qOver,
						uOver,
						divided,
						uShort,
						dividedToV,
						polynomial_division.DivisionUnique.Read(F).AsFact().At(r, p, w, v, q, u)))
			}))
		a.Take(u)
		a.Show(
			"the remainder of r is its one short representative",
			By(uOver, uShort, classOfU, unique))
	}),
})}

// IrreduciblePrincipalMaximal — an irreducible polynomial over a field
// generates a maximal ideal of the polynomials.
var IrreduciblePrincipalMaximal = irreduciblePrincipalMaximalThm{family.Add(registry.ProofEntry{
	Name: "IrreduciblePrincipalMaximal",
	Key:  "prop_413381a596d66530",
	Reading: "Irreducibility includes positive degree, which keeps the one polynomial " +
		"out of the ideal: its members are the multiples of p, of degree at least p's or zero.",
	Build: family.Theorem(Statement{
		Binders: "∀F:field_on(A). ∀p:(num → A).",
		Hypotheses: []string{
			"polynomial_irreducible(field_ring(F), p)",
		},
		Conclusion: "maximal_ideal(«fieldPolynomialRing», «idealOfP»)",
	}, func(a *Argument, F field.FieldFact[on.F], p *Expr[Fun[Nat, A]], irreducible Fact) {
		coefficients := a.TermAs[RingOps[A]]("field_ring(F)")
		polynomials := a.TermAs[RingOps[Fun[Nat, A]]]("«fieldPolynomialRing»")
		principal := a.TermAs[Set[Fun[Nat, A]]]("«idealOfP»")
		generator := a.TermAs[Set[Fun[Nat, A]]]("{p}")
		fieldRing := field.RingOn.Read(F)
		domain := integral_domain.FieldIntegralDomain.Read(F)
		pData := a.Have(
			"the irreducible polynomial has positive degree",
			"polynomial_over(F.carrier, p) ∧ 0 < polynomial_degree(p)",
			By(irreducible, polynomial_division.PolynomialIrreducibleDef.At(coefficients, p)))
		polynomialRing := a.Have(
			"the polynomials form a commutative ring",
			"comm_ring_on(«fieldPolynomialRing»)",
			By(polynomial.PolynomialRingOn.Read(fieldRing)))
		pInRing := a.Have(
			"the generator lies in the polynomial ring",
			"p ∈ «fieldPolynomialRing».carrier",
			Simp(Fwd(polynomial.PolynomialRingDef)),
			BySets(pData))
		ideal := a.Have(
			"the principal span is an ideal",
			"ring_ideal(«fieldPolynomialRing», «idealOfP»)",
			BySets(pData, ring_ideal.SpanIdeal.Read(polynomialRing).At(generator)))
		multiples := a.Have(
			"the principal ideal consists of polynomial multiples",
			"«idealOfP» = "+
				"{q:num → A | ∃r:num → A. r ∈ «fieldPolynomialRing».carrier ∧ q = «fieldPolynomialRing».mul(r, p)}",
			By(pInRing, ring_ideal.PrincipalIdealMultiples.Read(polynomialRing).AsFact().At(p)))
		proper := a.Have(
			"positive degree excludes the one polynomial",
			"«fieldPolynomialRing».one ∉ «idealOfP»",
			Derive(func(b *Argument) {
				b.Do(multiples.Rw(), Simp(Fwd(polynomial.PolynomialRingDef)))
				oneIsMultiple := b.SupposeNot()
				r, product := b.ObtainAs[Fun[Nat, A]](
					"write the one polynomial as a multiple",
					"∃r:num → A. polynomial_over(F.carrier, r) ∧ basis_vector(0) = polynomial_mul(r, p)",
					BySets(oneIsMultiple))
				nonzero := b.Have(
					"both factors of one are nonzero",
					"p ≠ vec_zero ∧ r ≠ vec_zero",
					By(
						Normalized,
						integral_domain.OneNotZero.Read(polynomial.PolynomialDomain.Read(domain)),
						pData,
						product,
						comm_ring.MulLeftZeroOn.Read(polynomialRing).AsFact().At(p),
						comm_ring.MulRightZeroOn.Read(polynomialRing).AsFact().At(r)))
				degreeZero := b.Have(
					"the product has degree zero",
					"polynomial_degree(polynomial_mul(r, p)) = 0",
					Derive(func(c *Argument) {
						parts := c.Conjuncts(
							product,
							"the multiplier is a polynomial",
							"the product is one")
						c.Show(
							"read the degree of the one polynomial",
							parts[1].RwRev(),
							By(field.OneNotZeroOn.Read(F), polynomial.DegreeBasisVector.Read(fieldRing).At(c.TermAs[Nat]("0"))))
					}))
				b.Show(
					"degree addition contradicts positive degree",
					ByArith(degreeZero, nonzero, pData, product, polynomial.DegreeMul.Read(domain).At(r, p)))
			}))
		maximal := a.Have(
			"a larger ideal contains the one polynomial",
			Statement{
				Binders: "∀J:set(num → A).",
				Hypotheses: []string{
					"ring_ideal(«fieldPolynomialRing», J)",
					"«idealOfP» ⊆ J",
				},
				Conclusion: "J = «idealOfP» ∨ «fieldPolynomialRing».one ∈ J",
			},
			Derive(func(b *Argument) {
				J := b.FixAs[Set[Fun[Nat, A]]]("J")
				above := b.Assume()
				strict := b.Unless(
					b.Term("J = «idealOfP»"),
					"the equal ideal already satisfies the conclusion",
					Given(func(c *Argument, equal Fact) {
						c.Show(
							"the two ideals coincide",
							By(equal))
					}))
				f, outside := b.ObtainAs[Fun[Nat, A]](
					"choose a polynomial outside the principal ideal",
					"∃f:num → A. f ∈ J ∧ f ∉ «idealOfP»",
					BySets(strict, above))
				inJ := b.Have(
					"J contains p and f has coefficients in the field",
					"p ∈ J ∧ polynomial_over(F.carrier, f)",
					BySets(
						above,
						outside,
						ring_ideal.SpanContains.At(polynomials, generator),
						ring_ideal.IdealSubset.At(polynomials, J)))
				notDivides := b.Have(
					"p does not divide the chosen polynomial",
					"¬polynomial_divides(field_ring(F), p, f)",
					Derive(func(c *Argument) {
						outsideParts := c.Conjuncts(
							outside,
							"f lies in the larger ideal",
							"f lies outside the principal ideal")
						pParts := c.Conjuncts(
							pData,
							"p has coefficients in the field",
							"p has positive degree")
						c.Do(Unfold(polynomial_division.PolynomialDividesDef))
						divides := c.SupposeNot()
						r, product := c.ObtainAs[Fun[Nat, A]](
							"take a hypothetical quotient",
							"∃r:num → A. polynomial_over(F.carrier, r) ∧ f = polynomial_mul(p, r)",
							By(divides))
						pInIdeal := c.Have(
							"the generator lies in its principal ideal",
							"p ∈ «idealOfP»",
							BySets(ring_ideal.SpanContains.At(polynomials, generator)))
						factorCoefficients := c.Have(
							"every coefficient of p and of the quotient lies in the field",
							"∀i:num. p(i) ∈ F.carrier ∧ r(i) ∈ F.carrier",
							By(pParts[0], product, polynomial.PolynomialOverDef))
						c.Show(
							"a divisible polynomial would lie in the principal ideal",
							By(
								Normalized,
								outsideParts[1],
								ideal,
								pInIdeal,
								product,
								pParts[0],
								factorCoefficients,
								polynomial.PolynomialMulComm.Read(fieldRing).At(p, r),
								ring_ideal.IdealMul.At(polynomials, principal, r, p)))
					}))
				u, v, bezout := b.Obtain2As[Fun[Nat, A], Fun[Nat, A]](
					"a Bezout identity expresses one using p and f",
					"∃u v:num → A. "+
						"    polynomial_over(F.carrier, u) ∧ "+
						"    polynomial_over(F.carrier, v) ∧ "+
						"    polynomial_mul(u, p) + polynomial_mul(v, f) = basis_vector(0)",
					By(notDivides, irreducible, inJ, polynomial_division.IrreducibleCoprime.Read(F).At(p, f)))
				products := b.Have(
					"J absorbs both terms in the Bezout identity",
					"polynomial_mul(u, p) ∈ J ∧ polynomial_mul(v, f) ∈ J",
					By(
						above,
						outside,
						inJ,
						bezout,
						ring_ideal.IdealMul.At(polynomials, J, u, p),
						ring_ideal.IdealMul.At(polynomials, J, v, f)))
				b.Show(
					"addition puts one in J",
					Simp(Fwd(polynomial.PolynomialRingDef)),
					By(
						above,
						products,
						bezout,
						ring_ideal.IdealAdd.At(polynomials, J,
							b.TermAs[Fun[Nat, A]]("polynomial_mul(u, p)"),
							b.TermAs[Fun[Nat, A]]("polynomial_mul(v, f)"))))
			}))
		a.Show(
			"properness and the larger-ideal criterion give maximality",
			By(proper, maximal, ideal, ring_ideal.MaximalIdealDef.At(polynomials, principal)))
	}),
})}

// QuotientClassIsEvaluation — modulo an ideal of the polynomials, the
// class of a polynomial is the polynomial evaluated at the class of the
// variable, its coefficients replaced by the classes of the constants:
// f is its own value at the variable, its coefficients read as constants
// (EvalAtVar), and the projection, a ring homomorphism, carries that
// value to the value of the projected coefficients at the projected
// variable (EvalAlongHomomorphism).
var QuotientClassIsEvaluation = quotientClassIsEvaluationThm{family.Add(registry.ProofEntry{
	Name: "QuotientClassIsEvaluation",
	Key:  "prop_bcc8caadb2df9ed9",
	Reading: "No condition on the ideal beyond being one: the ideal itself is the " +
		"quotient's zero, the class of every constant past f's length, so the coefficients " +
		"of the evaluated polynomial form a vector. At an f lying in I the left side is that " +
		"zero: the class of the variable is a root of f with its coefficients read as classes.",
	Build: family.Theorem(Statement{
		Binders: "∀R:comm_ring_on(A). ∀I:set(num → A). ∀f:(num → A).",
		Hypotheses: []string{
			"ring_ideal(polynomial_ring(R), I)",
			"polynomial_over(R.carrier, f)",
		},
		Conclusion: "ideal_quotient_projection(polynomial_ring(R), I, f) = " +
			"polynomial_eval(«Q».add, " +
			"    «Q».zero, " +
			"    «Q».mul, " +
			"    «Q».one, " +
			"    λi:num. ideal_quotient_projection(polynomial_ring(R), I, «C»(f(i))), " +
			"    ideal_quotient_projection(polynomial_ring(R), I, basis_vector(1)))",
		Abbrev: Abbrev{
			{Name: "Q", Text: "ideal_quotient_ring(polynomial_ring(R), I)"},
			{Name: "C", Text: "λa:A. a • basis_vector(0)"},
			{Name: "G", Text: "λi:num. «C»(f(i))"},
		},
	},
		func(
			a *Argument,
			R comm_ring.CommRingFact[on.R],
			I *Expr[Set[Fun[Nat, A]]],
			f *Arrow[Nat, A],
			hypotheses Fact,
		) {
			polynomials := a.TermAs[RingOps[Fun[Nat, A]]]("polynomial_ring(R)")
			variable := a.TermAs[Fun[Nat, A]]("basis_vector(1)")
			lifted := a.TermAs[Fun[Nat, Fun[Nat, A]]]("«G»")
			constants := polynomial.ConstantPolynomialHomomorphism.Read(R)
			parts := a.Conjuncts(
				hypotheses,
				"I is an ideal of the polynomial ring",
				"f is a polynomial over R")
			ideal, polynomialF := parts[0], parts[1]
			liftedPolynomial := a.Have(
				"the constant coefficients form a polynomial over P",
				"polynomial_over(polynomial_ring(R).zero, polynomial_ring(R).carrier, «G»)",
				By(
					polynomialF,
					ring_homomorphism.MapZero.Read(constants),
					ring_homomorphism.MapIn.Read(constants),
					polynomial.PolynomialOverMap.At(a.TermAs[Fun[A, Fun[Nat, A]]]("«C»"),
						a.TermAs[A]("R.zero"), a.TermAs[Fun[Nat, A]]("polynomial_ring(R).zero"),
						a.TermAs[Set[A]]("R.carrier"), a.TermAs[Set[Fun[Nat, A]]]("polynomial_ring(R).carrier"), f)))
			variableIn := a.Have(
				"the variable lies in the polynomial carrier",
				"basis_vector(1) ∈ polynomial_ring(R).carrier",
				By(R, polynomial.BasisVectorOver.Read(R).At(a.TermAs[Nat]("1"))))
			projection := a.Have(
				"the ideal projection is a ring homomorphism",
				"ring_homomorphism(polynomial_ring(R), «Q», ideal_quotient_projection(polynomial_ring(R), I))",
				By(
					ideal,
					polynomial.PolynomialRingOn.Read(R),
					quotient_ring.ProjectionHomomorphism.At(polynomials, I)))
			a.Show(
				"the projection carries f, its own value at the "+
					"variable, to the value at the class of the variable",
				CalcEq(
					Leg(
						a.TermAs[Set[Fun[Nat, A]]](
							"ideal_quotient_projection(polynomial_ring(R), "+
								"    I, "+
								"    polynomial_eval(vec_add, vec_zero, polynomial_mul, basis_vector(0), «G», basis_vector(1)))"),
						"f is its own value at the variable",
						By(Normalized, polynomialF, polynomial_evaluation.EvalAtVar.Read(R).At(f))),
					FinalLeg(
						"the projection, a ring homomorphism, carries a value to the "+
							"value of the projected coefficients at the projected point",
						By(
							liftedPolynomial,
							variableIn,
							polynomial_evaluation.EvalAlongHomomorphism.Read(projection).AsFact().At(lifted, variable))),
				))
		}),
})}

// QuotientConstantsEmbed — modulo a proper ideal of the polynomials over
// a field, the classes of the constants are a copy of the field: the
// constants followed by the ideal projection are a ring homomorphism, and
// a proper ideal holds no nonzero constant, a nonzero constant being a
// unit: times the constant of its inverse it is the one polynomial.
var QuotientConstantsEmbed = quotientConstantsEmbedThm{family.Add(registry.ProofEntry{
	Name: "QuotientConstantsEmbed",
	Key:  "prop_d7f74489997c47db",
	Reading: "Properness is load-bearing for injectivity only: modulo the whole " +
		"ring there is one class, and the homomorphism half holds for every ideal.",
	Build: family.Theorem(Statement{
		Binders: "∀F:field_on(A). ∀I:set(num → A).",
		Hypotheses: []string{
			"ring_ideal(«fieldPolynomialRing», I)",
			"«fieldPolynomialRing».one ∉ I",
		},
		Conclusion: "ring_homomorphism(field_ring(F), " +
			"    ideal_quotient_ring(«fieldPolynomialRing», I), " +
			"    «constantClass»(I)) ∧ " +
			"injective_on(F.carrier, «constantClass»(I))",
	},
		func(a *Argument, F field.FieldFact[on.F], I *Expr[Set[Fun[Nat, A]]], hypotheses Fact) {
			parts := a.Conjuncts(
				hypotheses,
				"I is an ideal of the polynomials",
				"the one polynomial lies outside I")
			ideal, proper := parts[0], parts[1]
			coefficients := a.TermAs[RingOps[A]]("field_ring(F)")
			polynomials := a.TermAs[RingOps[Fun[Nat, A]]]("«fieldPolynomialRing»")
			quotient := a.TermAs[RingOps[Set[Fun[Nat, A]]]]("ideal_quotient_ring(«fieldPolynomialRing», I)")
			constantMap := a.TermAs[Fun[A, Fun[Nat, A]]]("λa:A. a • basis_vector(0)")
			projectionMap := a.TermAs[Fun[Fun[Nat, A], Set[Fun[Nat, A]]]](
				"ideal_quotient_projection(«fieldPolynomialRing», I)")
			quotientMap := a.TermAs[Fun[A, Set[Fun[Nat, A]]]]("«constantClass»(I)")
			fieldRing := field.RingOn.Read(F)
			polynomialRing := polynomial.PolynomialRingOn.Read(fieldRing)
			constants := a.Have(
				"the constants enter the polynomial ring homomorphically",
				"ring_homomorphism(field_ring(F), «fieldPolynomialRing», λa:A. a • basis_vector(0))",
				By(polynomial.ConstantPolynomialHomomorphism.Read(fieldRing)))
			projection := a.Have(
				"the ideal projection is a ring homomorphism",
				"ring_homomorphism(«fieldPolynomialRing», "+
					"    ideal_quotient_ring(«fieldPolynomialRing», I), "+
					"    ideal_quotient_projection(«fieldPolynomialRing», I))",
				By(polynomialRing, ideal, quotient_ring.ProjectionHomomorphism.At(polynomials, I)))
			homomorphism := a.Have(
				"compose the constants with the ideal projection",
				"ring_homomorphism(field_ring(F), "+
					"    ideal_quotient_ring(«fieldPolynomialRing», I), "+
					"    «constantClass»(I))",
				By(
					constants,
					projection,
					ring_homomorphism.RingHomCompose.At(
						coefficients, polynomials, quotient, constantMap, projectionMap)))
			zeroConstants := a.Have(
				"a constant lying in I has coefficient zero",
				"∀a:A. a ∈ F.carrier ∧ a • basis_vector(0) ∈ I ⇒ a = F.zero",
				Derive(func(b *Argument) {
					coefficient := b.FixAs[A]("a")
					assumptions := b.Conjuncts(
						b.Assume(),
						"a lies in the field",
						"the constant of a lies in I")
					inField, inIdeal := assumptions[0], assumptions[1]
					nonzero := b.SupposeNot()
					inverse := b.TermAs[A]("F.inv(a)")
					inverseConstant := b.TermAs[Fun[Nat, A]]("F.inv(a) • basis_vector(0)")
					constant := b.TermAs[Fun[Nat, A]]("a • basis_vector(0)")
					inversePolynomial := b.Have(
						"the constant of the inverse is a polynomial",
						"F.inv(a) • basis_vector(0) ∈ «fieldPolynomialRing».carrier",
						By(
							inField,
							field.InvIn.Read(F).AsFact().At(coefficient),
							ring_homomorphism.MapIn.Read(constants).AsFact().At(inverse)))
					productInIdeal := b.Have(
						"I holds the constant of the inverse times the constant of a",
						"polynomial_mul(F.inv(a) • basis_vector(0), a • basis_vector(0)) ∈ I",
						By(
							inversePolynomial,
							ideal,
							inIdeal,
							ring_ideal.IdealMul.At(polynomials, I, inverseConstant, constant)))
					productIsOne := b.Have(
						"the constant of the inverse times the constant of a is the one polynomial",
						"polynomial_mul(F.inv(a) • basis_vector(0), a • basis_vector(0)) = «fieldPolynomialRing».one",
						Simp(Fwd(polynomial.PolynomialRingDef)),
						By(
							nonzero,
							inField,
							field.InvIn.Read(F).AsFact().At(coefficient),
							field.MulLeftInverseOn.Read(F).AsFact().At(coefficient),
							ring_homomorphism.MapMul.Read(constants).AsFact().At(inverse, coefficient),
							ring_homomorphism.MapOne.Read(constants)))
					b.Show(
						"the one polynomial lies in I and outside it",
						By(productIsOne, productInIdeal, proper))
				}))
			zeroClass := a.Have(
				"a constant in the quotient zero class is zero",
				"∀a:A. a ∈ F.carrier ∧ «constantClass»(I, a) = I ⇒ a = F.zero",
				Derive(func(b *Argument) {
					coefficient := b.FixAs[A]("a")
					zeroImage := b.Assume()
					constant := b.TermAs[Fun[Nat, A]]("a • basis_vector(0)")
					b.Show(
						"the zero coset criterion puts the constant in the ideal",
						By(
							polynomialRing,
							zeroConstants.At(coefficient),
							ideal,
							zeroImage,
							ring_homomorphism.MapIn.Read(constants).AsFact().At(coefficient),
							quotient_ring.CosetEqIdealIff.At(polynomials, I, constant),
							quotient_ring.IdealQuotientProjectionDef.At(polynomials, I, constant)))
				}))
			kernel := a.Have(
				"the additive kernel is the singleton zero",
				"group_kernel(I, F.carrier, «constantClass»(I)) = {F.zero}",
				BySets(
					Normalized,
					comm_ring.ZeroIn.Read(fieldRing),
					ring_homomorphism.MapZero.Read(homomorphism),
					zeroClass,
					group_homomorphism.GroupKernelDef.At(I, a.TermAs[Set[A]]("F.carrier"), quotientMap)))
			a.Show(
				"the constant classes form an injective ring homomorphism",
				By(
					homomorphism,
					group_homomorphism.KernelTrivialIffInjective.Read(
						ring_homomorphism.AdditiveHomomorphism.Read(homomorphism)),
					kernel))
		}),
})}

// QuotientAlgebraicExtension — modulo an irreducible polynomial p, the
// polynomials over a field F are a field, into which the classes of the
// constants embed F as a ring; the class ξ of the variable lies in it and
// is a root of pQ, p with its coefficients carried to their classes; and
// the classes of the constants form a subfield over which every class is
// algebraic. The ideal of p is maximal, so the quotient is a field and
// the constants embed (QuotientConstantsEmbed); the class of p is pQ
// evaluated at ξ (QuotientClassIsEvaluation), and it is zero, p lying in
// its ideal. pQ is a nonzero polynomial over the constant classes, and
// every class is the value at ξ of a polynomial over them, so it lies in
// the subfield of the points algebraic over the constant classes, which
// holds ξ.
var QuotientAlgebraicExtension = quotientAlgebraicExtensionThm{family.Add(registry.ProofEntry{
	Name: "QuotientAlgebraicExtension",
	Key:  "prop_d18fd5c9d91f11f3",
	Build: family.Theorem(Statement{
		Binders: "∀F:field_on(A). ∀p:(num → A).",
		Hypotheses: []string{
			"polynomial_irreducible(field_ring(F), p)",
		},
		Conclusion: "field_on(«rootField») ∧ " +
			"ring_homomorphism(field_ring(F), field_ring(«rootField»), «constantClass»(«idealOfP»)) ∧ " +
			"injective_on(F.carrier, «constantClass»(«idealOfP»)) ∧ " +
			"«variableClass» ∈ «rootField».carrier ∧ " +
			"polynomial_eval(«rootField».add, " +
			"    «rootField».zero, " +
			"    «rootField».mul, " +
			"    «rootField».one, " +
			"    λi:num. «constantClass»(«idealOfP», p(i)), " +
			"    «variableClass») = " +
			"«rootField».zero ∧ " +
			"subfield(«rootField», «constantClasses») ∧ " +
			"(∀y:set(num → A). y ∈ «rootField».carrier ⇒ algebraic_over(«rootField», «constantClasses», y))",
	}, func(a *Argument, F field.FieldFact[on.F], p *Arrow[Nat, A], irreducible Fact) {
		polynomials := a.TermAs[RingOps[Fun[Nat, A]]]("«fieldPolynomialRing»")
		ideal := a.TermAs[Set[Fun[Nat, A]]]("«idealOfP»")
		quotient := a.TermAs[FieldOps[Set[Fun[Nat, A]]]]("«rootField»")
		embedding := a.TermAs[Fun[A, Set[Fun[Nat, A]]]]("«constantClass»(«idealOfP»)")
		base := a.TermAs[Set[Set[Fun[Nat, A]]]]("«constantClasses»")
		fieldCarrier := a.TermAs[Set[A]]("F.carrier")
		fieldZero := a.TermAs[A]("F.zero")
		sourceRing := field.RingOn.Read(F)
		polynomialRing := polynomial.PolynomialRingOn.Read(sourceRing)
		quotientDef := Fwd(quotient_ring.IdealQuotientFieldDef.Inst[Fun[Nat, A]]())
		maximal := a.Have(
			"the irreducible polynomial generates a maximal ideal",
			"maximal_ideal(«fieldPolynomialRing», «idealOfP»)",
			By(irreducible, IrreduciblePrincipalMaximal.Read(F).At(p)))
		properIdeal := a.Have(
			"the maximal ideal is proper",
			"ring_ideal(«fieldPolynomialRing», «idealOfP») ∧ «fieldPolynomialRing».one ∉ «idealOfP»",
			By(maximal, ring_ideal.MaximalIdealDef.At(polynomials, ideal)))
		idealParts := a.Conjuncts(
			properIdeal,
			"the principal set is an ideal",
			"the one polynomial is outside the principal ideal")
		isIdeal, proper := idealParts[0], idealParts[1]
		fieldOn := a.Have(
			"the quotient is a field",
			"field_on(«rootField»)",
			By(maximal, quotient_ring.QuotientFieldOn.Read(polynomialRing).AsFact().At(ideal)))
		constants := a.Have(
			"the constant classes give an injective ring map",
			"ring_homomorphism(field_ring(F), "+
				"    ideal_quotient_ring(«fieldPolynomialRing», «idealOfP»), "+
				"    «constantClass»(«idealOfP»)) ∧ "+
				"injective_on(F.carrier, «constantClass»(«idealOfP»))",
			By(isIdeal, proper, QuotientConstantsEmbed.Read(F).At(ideal)))
		constantParts := a.Conjuncts(
			constants,
			"the constants preserve ring operations",
			"the constants map is injective")
		injective := constantParts[1]
		hom := a.Have(
			"the constants map lands in the quotient field ring",
			"ring_homomorphism(field_ring(F), field_ring(«rootField»), «constantClass»(«idealOfP»))",
			Simp(Fwd(quotient_ring.IdealQuotientFieldRing)),
			By(constantParts[0]))
		projectionData := a.Have(
			"the ideal projection is a surjective ring map",
			"ring_homomorphism(«fieldPolynomialRing», "+
				"    ideal_quotient_ring(«fieldPolynomialRing», «idealOfP»), "+
				"    ideal_quotient_projection(«fieldPolynomialRing», «idealOfP»)) ∧ "+
				"image(ideal_quotient_projection(«fieldPolynomialRing», «idealOfP»), "+
				"    «fieldPolynomialRing».carrier) = "+
				"ideal_quotient_ring(«fieldPolynomialRing», «idealOfP»).carrier",
			By(polynomialRing, isIdeal, quotient_ring.IdealQuotientProjection.At(polynomials, ideal)))
		projectionParts := a.Conjuncts(
			projectionData,
			"the ideal projection preserves ring operations",
			"the ideal projection covers its quotient ring")
		variable, variableDef := a.LetAs[Set[Fun[Nat, A]]]("ξ", "«variableClass»")
		variableIn := a.Have(
			"the variable class lies in the quotient field",
			"ξ ∈ «rootField».carrier",
			Simp(Fwd(variableDef)),
			By(
				ring_homomorphism.MapIn.Read(projectionParts[0]).AsFact().At(
					a.TermAs[Fun[Nat, A]]("basis_vector(1)")),
				polynomial.BasisVectorOver.Read(sourceRing).At(a.TermAs[Nat]("1"))))
		irreducibleData := a.Conjuncts(
			a.Unfolded(irreducible, polynomial_division.PolynomialIrreducibleDef),
			"the defining sequence is a polynomial",
			"the defining polynomial has positive degree",
			"its factorizations have a constant factor")
		pOver, positiveDegree := irreducibleData[0], irreducibleData[1]
		pNonzero := a.Have(
			"a polynomial of positive degree is nonzero",
			"p ≠ vec_zero",
			Derive(func(b *Argument) {
				vanishes := b.SupposeNot()
				degreeZero := b.Have(
					"a vanishing polynomial has degree zero",
					"polynomial_degree(p) = 0",
					By(Normalized, vanishes, polynomial.DegreeVecZero.At(fieldZero)))
				b.Show(
					"positive degree excludes this equality",
					ByArith(positiveDegree, degreeZero))
			}))
		zero := a.Have(
			"the constants map preserves zero",
			"«constantClass»(«idealOfP», F.zero) = «rootField».zero",
			By(ring_homomorphism.MapZero.Read(hom)))
		intoBase := a.Have(
			"every constant class lies in the constants image",
			"∀a:A. a ∈ F.carrier ⇒ «constantClass»(«idealOfP», a) ∈ «constantClasses»",
			Derive(func(b *Argument) {
				coefficient := b.FixAs[A]("a")
				inField := b.Assume()
				b.Show(
					"the image of F holds the class of each of its points",
					By(inField, set_image.FunInImage.At(embedding, fieldCarrier, coefficient)))
			}))
		quotientZero := a.TermAs[Set[Fun[Nat, A]]]("«rootField».zero")
		mappedPolynomial := a.Have(
			"mapping coefficients gives a polynomial over the constants image",
			Statement{
				Binders: "∀f:(num → A).",
				Hypotheses: []string{
					"polynomial_over(F.carrier, f)",
				},
				Conclusion: "polynomial_over(«rootField».zero, " +
					"    «constantClasses», " +
					"    λi:num. «constantClass»(«idealOfP», f(i)))",
			},
			Derive(func(b *Argument) {
				f := b.FixAs[Fun[Nat, A]]("f")
				fOver := b.Assume()
				b.Show(
					"the constants map sends F.zero to the quotient zero and F into the constants image",
					By(
						fOver,
						zero,
						intoBase,
						polynomial.PolynomialOverMap.At(embedding, fieldZero, quotientZero, fieldCarrier, base, f)))
			}))
		baseField := a.Have(
			"the image of the constants is a subfield",
			"subfield(«rootField», «constantClasses»)",
			By(fieldOn, hom, ring_homomorphism.ImageSubfield.Read(F).At(quotient, embedding)))
		pInIdeal := a.Have(
			"the generator belongs to its principal ideal",
			"p ∈ «idealOfP»",
			BySets(ring_ideal.SpanContains.At(polynomials, a.TermAs[Set[Fun[Nat, A]]]("{p}"))))
		pProjectsToZero := a.Have(
			"the defining polynomial has zero quotient class",
			"ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», p) = «idealOfP»",
			Simp(Fwd(quotient_ring.IdealQuotientProjectionDef.Inst[Fun[Nat, A]]())),
			By(
				isIdeal,
				pInIdeal,
				pOver,
				quotient_ring.CosetEqIdealIff.Read(polynomialRing).AsFact().At(ideal, p)))
		evaluation := a.Have(
			"every polynomial class is evaluation at the variable class",
			Statement{
				Binders: "∀f:(num → A).",
				Hypotheses: []string{
					"polynomial_over(F.carrier, f)",
				},
				Conclusion: "ideal_quotient_projection(«fieldPolynomialRing», «idealOfP», f) = " +
					"polynomial_eval(«rootField».add, " +
					"    «rootField».zero, " +
					"    «rootField».mul, " +
					"    «rootField».one, " +
					"    λi:num. «constantClass»(«idealOfP», f(i)), " +
					"    ξ)",
			},
			Derive(func(b *Argument) {
				f := b.FixAs[Fun[Nat, A]]("f")
				fOver := b.Assume()
				b.Show(
					"the class of a polynomial is its value at the class of the variable",
					Simp(quotientDef, Fwd(variableDef)),
					By(isIdeal, fOver, QuotientClassIsEvaluation.Read(sourceRing).At(ideal, f)))
			}))
		evaluationExpanded := a.Simplified(evaluation, quotientDef)
		mapped, mappedDef := a.LetAs[Fun[Nat, Set[Fun[Nat, A]]]](
			"pQ", "λi:num. «constantClass»(«idealOfP», p(i))")
		root := a.Have(
			"the variable class is a root of the mapped defining polynomial",
			"polynomial_eval(«rootField».add, «rootField».zero, «rootField».mul, «rootField».one, pQ, ξ) = "+
				"«rootField».zero",
			Simp(quotientDef, Fwd(mappedDef)),
			By(evaluationExpanded.At(p), pOver, pProjectsToZero))
		mappedNonzero := a.Have(
			"the mapped defining polynomial is nonzero",
			"pQ ≠ vec_zero(«rootField».zero)",
			Simp(Fwd(mappedDef)),
			By(
				pOver,
				comm_ring.ZeroIn.Read(sourceRing),
				injective,
				zero,
				pNonzero,
				polynomial.PolynomialMapNonzero.At(embedding, fieldZero, quotientZero, fieldCarrier, p)))
		mappedOver := a.Have(
			"the mapped defining polynomial is a polynomial over the constants image",
			"polynomial_over(«rootField».zero, «constantClasses», pQ)",
			Simp(Fwd(mappedDef)),
			By(mappedPolynomial.At(p), pOver))
		mappedPolynomialExpanded := a.Simplified(mappedPolynomial, quotientDef)
		mappedOverExpanded := a.Simplified(mappedOver, quotientDef)
		rootExpanded := a.Simplified(root, quotientDef)
		mappedNonzeroExpanded := a.Simplified(mappedNonzero, quotientDef)
		variableAlgebraic := a.Have(
			"the mapped defining polynomial witnesses algebraicity",
			"algebraic_over(«rootField», «constantClasses», ξ)",
			Simp(Fwd(algebraic_element.AlgebraicOverDef.Inst[Set[Fun[Nat, A]]]())),
			Witness(mapped),
			By(mappedOverExpanded, mappedNonzeroExpanded, rootExpanded))
		surjective := a.Have(
			"the polynomial projection covers the quotient field",
			"image(ideal_quotient_projection(«fieldPolynomialRing», «idealOfP»), "+
				"    «fieldPolynomialRing».carrier) = "+
				"«rootField».carrier",
			By(
				projectionParts[1],
				quotient_ring.IdealQuotientFieldDef.At(polynomials, ideal),
				quotient_ring.IdealQuotientRingDef.At(polynomials, ideal)))
		values := a.Have(
			"every quotient point is a polynomial value over the constants",
			"«rootField».carrier ⊆ polynomial_image(field_ring(«rootField»), «constantClasses», ξ)",
			Derive(func(b *Argument) {
				b.Do(
					surjective.RwRev(),
					Simp(Fwd(set_image.ImageSubsetIff.Inst(
						TypeBinder.BindA[Fun[Nat, A]](), TypeBinder.BindB[Set[Fun[Nat, A]]]()))))
				f := b.FixAs[Fun[Nat, A]]("f")
				inRing := b.Assume()
				fOver := b.Have(
					"the representative is a polynomial over F",
					"polynomial_over(F.carrier, f)",
					By(inRing))
				b.Do(
					Simp(Fwd(algebraic_element.PolynomialImageDef.Inst[Set[Fun[Nat, A]]]()), quotientDef),
					Unfold(set_basic.SetMemberDef),
					Unfold(set_basic.SetComprehensionDef),
					Unfold(set_basic.ComprehensionSpecDef))
				b.Take(b.TermAs[Fun[Nat, Set[Fun[Nat, A]]]]("λi:num. «constantClass»(«idealOfP», f(i))"))
				b.Show(
					"use the mapped coefficients and the quotient evaluation identity",
					By(mappedPolynomialExpanded.At(f), evaluationExpanded.At(f), fOver))
			}))
		alg, algDef := a.LetAs[Set[Set[Fun[Nat, A]]]](
			"Alg", "algebraic_elements(«rootField», «constantClasses»)")
		algebraicPoints := algebraic_element.AlgebraicElementsDef.Inst[Set[Fun[Nat, A]]]()
		algebraicSubfield := a.Have(
			"the algebraic elements form a subfield containing the base",
			"subfield(«rootField», Alg) ∧ «constantClasses» ⊆ Alg",
			Simp(Fwd(algDef)),
			By(baseField, algebraic_element.AlgebraicElementsSubfield.Read(fieldOn).At(base)))
		algebraicParts := a.Conjuncts(
			algebraicSubfield,
			"the algebraic elements are a subfield",
			"the algebraic elements contain the base")
		restrictedRing := a.Have(
			"the algebraic subfield carries the restricted ring",
			"comm_ring_on(restrict_ring(field_ring(«rootField»), Alg))",
			By(algebraicParts[0], field.SubfieldCommRing.Read(fieldOn).At(alg)))
		variableInAlg := a.Have(
			"the variable class belongs to the algebraic subfield",
			"ξ ∈ Alg",
			BySets(variableIn, variableAlgebraic, algDef, algebraicPoints))
		polynomialImage := a.Have(
			"polynomial values stay inside the algebraic subfield",
			"polynomial_image(field_ring(«rootField»), «constantClasses», ξ) ⊆ Alg",
			By(
				restrictedRing,
				algebraicParts[1],
				variableInAlg,
				algebraic_element.PolynomialImageLeast.Read(fieldOn).At(base, alg, variable)))
		allAlgebraic := a.Have(
			"every quotient point is algebraic over the constants",
			"∀y:set(num → A). y ∈ «rootField».carrier ⇒ algebraic_over(«rootField», «constantClasses», y)",
			Derive(func(b *Argument) {
				b.FixAs[Set[Fun[Nat, A]]]("y")
				inQuotient := b.Assume()
				inAlg := b.Have(
					"the point lies in the algebraic subfield",
					"y ∈ Alg",
					BySets(inQuotient, values, polynomialImage))
				b.Show(
					"a point of Alg is algebraic over the constants",
					BySets(inAlg, algDef, algebraicPoints))
			}))
		a.Show(
			"the quotient is a field holding a copy of F and a root of pQ, algebraic over the copy",
			By(fieldOn, hom, injective, variableIn, root, baseField, allAlgebraic))
	}),
})}
