// IntegralAddNeg — sums and additive inverses of algebraic integers are
// algebraic integers: they lie in the ring the two generate over the integer
// image, and that ring consists of algebraic integers.
var IntegralAddNeg = integralAddNegThm{family.Add(registry.ProofEntry{
	Name: "IntegralAddNeg",
	Key:  "prop_93d8104ef3aa20aa",
	Build: family.Theorem(Statement{
		Binders: "∀L:field_on(A). ∀x y:A.",
		Hypotheses: []string{
			"number_field(L)",
			"x ∈ ring_of_integers(field_ring(L))",
			"y ∈ ring_of_integers(field_ring(L))",
		},
		Conclusion: "x + y ∈ ring_of_integers(field_ring(L)) ∧ -x ∈ ring_of_integers(field_ring(L))",
	}, func(a *Argument, L field.FieldFact[on.L], x, y *Expr[A], h Fact) {
		parts := a.Conjuncts(
			h,
			"L is a number field",
			"x is an algebraic integer",
			"y is an algebraic integer")
		numberField, integerX, integerY := parts[0], parts[1], parts[2]
		integers, generators := a.TermAs[Set[A]]("integer_image(field_ring(L))"), a.TermAs[Set[A]]("{x, y}")
		fieldL := a.TermAs[FieldOps[A]]("L")
		scalars := a.Conjuncts(
			GroupPremises(L, parts[0], number_field.NumberFieldScalars.At(fieldL)),
			"L has characteristic zero",
			"its rational image is a subfield",
			"the integer image lies in the rational image",
			"the integer image is a commutative ring",
			"and a principal ideal domain",
			"L is a module over the integer image",
			"and over the rational image")
		integerRing := scalars[3]
		inField := a.Have(
			"the integer image lies in the field",
			"integer_image(field_ring(L)) ⊆ L.carrier",
			Simp(Fwd(characteristic_zero.IntegerImageDef)),
			By(characteristic_zero.IntegerMapHom.Read(field.RingOn.Read(L))))
		integerSubring := a.Have(
			"the integer image is a subring of the field",
			"subring(field_ring(L), integer_image(field_ring(L)))",
			By(inField, integerRing, comm_ring.SubringRingOn.Read(field.RingOn.Read(L)).At(integers)))
		finiteGenerators := a.Have(
			"two generators form a finite set",
			"finite({x, y})",
			Simp(Fwd(finite_set.FiniteInsert)),
			By(finite_set.FiniteRules))
		carriers := a.Have(
			"x and y lie in the field",
			"x ∈ L.carrier ∧ y ∈ L.carrier",
			BySets(integerX, integerY, RingOfIntegersDef))
		generatorsIn := a.Have(
			"both generators are algebraic integers of the field",
			"{x, y} ⊆ ring_of_integers(field_ring(L)) ∧ {x, y} ⊆ L.carrier",
			Simp(Fwd(set_order.InsertSubset), Fwd(set_order.EmptySubset)),
			By(integerX, integerY, carriers))
		defM := a.Let(
			"M", a.TermAs[Set[A]]("generated_subring(field_ring(L), integer_image(field_ring(L)), {x, y})"))
		subring := a.Have(
			"the ring generated by x and y is a subring of the field holding them",
			"subring(field_ring(L), M) ∧ integer_image(field_ring(L)) ∪ {x, y} ⊆ M",
			By(
				Normalized,
				defM,
				integerSubring,
				generatorsIn,
				algebraic_element.GeneratedSubringStructure.Read(L).At(integers, generators)))
		subringParts := a.Conjuncts(
			subring,
			"M is a subring of the field",
			"M holds the integer image, x and y")
		subringM, generated := subringParts[0], subringParts[1]
		formedIn := a.Have(
			"its addition and additive inverses keep the sum and the negative in the ring",
			"x + y ∈ M ∧ -x ∈ M",
			generated.Simp(Fwd(set_order.UnionSubset), Fwd(set_order.InsertSubset), Fwd(set_order.EmptySubset)),
			By(generated, comm_ring.SubringAdd.Read(subringM), comm_ring.SubringNeg.Read(subringM)))
		integralRing := a.Have(
			"the ring generated by x and y consists of algebraic integers",
			"M ⊆ ring_of_integers(field_ring(L))",
			By(
				Normalized,
				defM,
				numberField,
				finiteGenerators,
				generatorsIn,
				GeneratedSubringIntegral.Read(L).At(generators)))
		a.Show(
			"the sum and negative are algebraic integers",
			BySets(formedIn, integralRing))
	}),
})}

