// PullbackSigmaDef — `pullback_sigma(Ω, f, T)` is the family of inverse
// images on Ω of the members of T: f⁻¹T. When f maps Ω into the carrier
// of a σ-algebra T, it is the least σ-algebra on Ω that makes f
// measurable.
var PullbackSigmaDef = pullbackSigmaDefThm{family.Define(registry.DefEntry{
	Name:  "PullbackSigmaDef",
	Key:   "prop_fe1f3555bdd26056",
	Const: "pullback_sigma",
	Type:  "set(A) → (A → B) → set(set(B)) → set(set(A))",
	Equations: []string{
		"∀Ω:set(A). ∀f:(A → B). ∀T:set(set(B)). " +
			"    pullback_sigma(Ω, f, T) = image(λt:set(B). preimage_on(Ω, f, t), T)",
	},
})}

// CoordinateSigmaDef — `coordinate_sigma(Ω, X, T, K)` is the σ-algebra on
// Ω that the coordinates i ∈ K of a map X from Ω into families generate,
// each coordinate read against its own σ-algebra T(i). The σ-algebra
// of a group of variables is this one.
var CoordinateSigmaDef = coordinateSigmaDefThm{family.Define(registry.DefEntry{
	Name:  "CoordinateSigmaDef",
	Key:   "prop_3217db0d0de1b314",
	Const: "coordinate_sigma",
	Type:  "set(A) → (A → I → B) → (I → set(set(B))) → set(I) → set(set(A))",
	Equations: []string{
		"∀Ω:set(A). ∀X:(A → I → B). ∀T:(I → set(set(B))). ∀K:set(I). " +
			"    coordinate_sigma(Ω, X, T, K) = sigma_join(Ω, λi:I. pullback_sigma(Ω, λu:A. X(u, i), T(i)), K)",
	},
	Deps: []registry.EntryLike{PullbackSigmaDef},
})}

