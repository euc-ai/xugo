// ConjMember — the conjugate of a Gaussian integer is a Gaussian integer:
// its parts are re(z) and −im(z).
var ConjMember = conjMemberThm{family.Add(registry.ProofEntry{
	Name: "ConjMember",
	Key:  "prop_5c1047586010b3a0",
	Build: family.Theorem(Statement{
		Binders:    "∀z:complex.",
		Hypotheses: []string{"z ∈ gaussian_integers"},
		Conclusion: "conj(z) ∈ gaussian_integers",
	}, func(a *Argument, z *Expr[Complex], member Fact) {
		a.Show(
			"the parts of conj(z) are re(z) and the negated im(z), integers when those of z are",
			By(
				member,
				MemberIffIntegerParts.At(z),
				MemberIffIntegerParts.At(a.TermAs[Complex]("conj(z)")),
				complex_field.PartsConj.At(z),
				int_construction.IntegerClosedUnderNeg))
	}),
})}

// NormOneUnit — a Gaussian integer of norm one is a unit of ℤ[i]: its
// conjugate is a Gaussian integer, and z times conj(z) is the norm.
var NormOneUnit = normOneUnitThm{family.Add(registry.ProofEntry{
	Name: "NormOneUnit",
	Key:  "prop_c0c2a16ac8bd3a34",
	Build: family.Theorem(Statement{
		Binders: "∀z:complex.",
		Hypotheses: []string{
			"z ∈ gaussian_integers",
			"gaussian_norm(z) = 1",
		},
		Conclusion: "ring_unit(gaussian_ring, z)",
	}, func(a *Argument, z *Expr[Complex], member, normOne Fact) {
		inverse := a.Have(
			"z times its conjugate is its norm, which is one",
			"z * conj(z) = &1",
			By(member, normOne, complex_field.MulConj.At(z), NormReal.At(z)))
		a.Show(
			"conj(z) is an inverse of z in ℤ[i]",
			Unfold(ring_ideal.RingUnitDef),
			By(member, inverse, ConjMember.At(z)))
	}),
})}

// MultipleWithUnitImaginaryPart — a natural number other than 1 divides
// neither m + i nor m − i in ℤ[i]: the imaginary part of p w is p times
// the integer im(w), whose absolute value is a natural k, and p k = 1
// only for p = 1, while m ± i has imaginary part ±1.
var MultipleWithUnitImaginaryPart = multipleWithUnitImaginaryPartThm{family.Add(registry.ProofEntry{
	Name: "MultipleWithUnitImaginaryPart",
	Key:  "prop_a3096b27424b3577",
	Build: family.Theorem(Statement{
		Binders: "∀p m:num. ∀w:complex.",
		Hypotheses: []string{
			"p ≠ 1",
			"w ∈ gaussian_integers",
		},
		Conclusion: "complex(&m, &1) ≠ complex_of_real(&p) * w ∧ " +
			"complex(&m, -&1) ≠ complex_of_real(&p) * w",
	}, func(a *Argument, p, m *Expr[Nat], w *Expr[Complex], notOne, member Fact) {
		imaginary := a.Have(
			"the imaginary part of p w is p im(w)",
			"im(complex_of_real(&p) * w) = &p * im(w)",
			Simp(Fwd(complex_field.ComplexMulDef), Fwd(complex_field.ComplexOfRealDef)),
			ByArith())
		k, absolute := a.ObtainAs[Nat](
			"im(w) is an integer, so its absolute value is a natural k",
			"∃k:num. |im(w)| = &k",
			By(member, MemberIffIntegerParts.At(w), int_construction.IntegerDef.At(a.TermAs[Real]("im(w)"))))
		// real_of_num spelled out: no operand of this claim fixes the codomain of `&`.
		notUnit := a.Have(
			"p k is not 1, since in ℕ a product is one only when both factors are",
			"real_of_num(p) * real_of_num(k) ≠ &1",
			By(
				Normalized,
				notOne,
				real_construction.OfNumMul.At(p, k),
				real_construction.OfNumEq.At(a.TermAs[Nat]("p * k"), a.TermAs[Nat]("1")),
				nat_arith.MulEqOne.At(p, k)))
		notUnitPart := a.Have(
			"so |im(p w)| = p k is not 1",
			"|im(complex_of_real(&p) * w)| ≠ &1",
			ByArith(imaginary, Scaled(a.TermAs[Real]("real_of_num(p)"), absolute), notUnit))
		a.Show(
			"while m ± i has imaginary part ±1, and equal complex numbers have equal parts",
			Simp(complex_field.Parts),
			ByArith(imaginary, notUnitPart))
	}),
})}

// PrimeDividingSquarePlusOne — a prime that divides m² + 1 is a sum of two
// squares. In ℤ[i], p and m + i span a principal ideal, generated by some
// α; p = α β, so N(α) N(β) = p², and N(α) is 1, p or p². If N(α) = 1, α is
// a unit, 1 = u p + v (m + i), and multiplying by m − i makes p divide
// m − i. If N(α) = p², β is a unit, α is p times a Gaussian integer, and p
// divides m + i. Neither can be: no natural number other than 1 divides
// m ± i in ℤ[i]. So N(α) = p: the parts of α are integers, their squares
// are the squares of natural numbers r and s, and p = r² + s².
var PrimeDividingSquarePlusOne = primeDividingSquarePlusOneThm{family.Add(registry.ProofEntry{
	Name: "PrimeDividingSquarePlusOne",
	Key:  "prop_5a954508e6f305ef",
	Build: family.Theorem(Statement{
		Binders: "∀p m:num.",
		Hypotheses: []string{
			"nat_prime(p)",
			"p ∣ m * m + 1",
		},
		Conclusion: "∃a b:num. p = a * a + b * b",
		Abbrev: Abbrev{
			{Name: "m + i", Text: "complex(&m, &1)"},
			{Name: "m − i", Text: "complex(&m, -&1)"},
			{Name: "Span", Text: "ideal_span(gaussian_ring, {complex_of_real(&p), «m + i»})"},
			{Name: "(m + i)", Text: "ideal_span(gaussian_ring, {«m + i»})"},
		},
	}, func(arg *Argument, p, m *Expr[Nat], prime, divides Fact) {
		ring := integral_domain.Ring.Read(IntegralDomain)
		gaussianRing := arg.TermAs[module_record.RingOps[Complex]]("gaussian_ring")
		complexRing := arg.TermAs[module_record.RingOps[Complex]]("complex_ring")
		gaussianIntegers := arg.TermAs[Set[Complex]]("gaussian_integers")
		pi := arg.TermAs[Complex]("complex_of_real(&p)")
		mu := arg.TermAs[Complex]("«m + i»")
		generators := arg.TermAs[Set[Complex]]("{complex_of_real(&p), «m + i»}")
		piIn := arg.MemberOf[on.Any](pi, arg.Have(
			"p is a Gaussian integer",
			"complex_of_real(&p) ∈ gaussian_integers",
			By(MemberIffIntegerParts.At(pi), complex_field.PartsOfReal, int_construction.IntegerOfNum)))
		muIn := arg.MemberOf[on.Any](mu, arg.Have(
			"m + i is a Gaussian integer",
			"«m + i» ∈ gaussian_integers",
			By(MemberIffIntegerParts.At(mu), int_construction.IntegerOfNum)))
		inside := arg.Have(
			"so the two lie in ℤ[i]",
			"{complex_of_real(&p), «m + i»} ⊆ gaussian_integers",
			BySets(piIn, muIn))
		ideal := arg.Have(
			"p and m + i span an ideal of ℤ[i]",
			"ring_ideal(gaussian_ring, «Span»)",
			By(inside, ring_ideal.SpanIdeal.Read(ring).At(generators)))
		alpha, generated := arg.ObtainAs[Complex](
			"ℤ[i] is a principal ideal domain, so a single α generates that ideal",
			"∃α:complex. α ∈ gaussian_integers ∧ «Span» = image(complex_mul(α), gaussian_integers)",
			By(ideal, PrincipalIdealDomain, principal_ideal_domain.PrincipalIdealDomainDef.At(gaussianRing)))
		generator := arg.Conjuncts(
			generated,
			"α is a Gaussian integer",
			"the ideal consists of the multiples of α")
		beta, betaFact := arg.ObtainAs[Complex](
			"p lies in the ideal, so p = α β with β in ℤ[i]",
			"∃β:complex. β ∈ gaussian_integers ∧ complex_of_real(&p) = α * β",
			BySets(generator[1], ring_ideal.SpanContains.At(gaussianRing, generators)))
		inReals := arg.Have(
			"read in ℝ, the norm of p is p p plus 0 0",
			"real_of_num(gaussian_norm(complex_of_real(&p))) = real_of_num(p) * real_of_num(p)",
			ByArith(piIn, complex_field.PartsOfReal.At(arg.TermAs[Real]("&p")), NormReal.At(pi)))
		pSquare := arg.Have(
			"so the norm of p is p p",
			"gaussian_norm(complex_of_real(&p)) = p * p",
			By(inReals, real_construction.OfNumEq, real_construction.OfNumMul))
		product := arg.Have(
			"the norm is multiplicative, so N(α) N(β) = p p",
			"gaussian_norm(α) * gaussian_norm(β) = p * p",
			By(Normalized, pSquare, generator[0], betaFact, NormMul.At(alpha, beta)))
		normOneSquareOrP := arg.Have(
			"N(α) is a factor of p p, so it is 1, p p or p",
			"gaussian_norm(α) = 1 ∨ gaussian_norm(α) = p * p ∨ gaussian_norm(α) = p",
			By(
				prime,
				product,
				nat_prime.FactorOfPrimeSquare.At(
					p, arg.TermAs[Nat]("gaussian_norm(α)"), arg.TermAs[Nat]("gaussian_norm(β)"))))
		arg.Show(
			"N(α) = 1 and N(α) = p p are impossible, which leaves N(α) = p",
			normOneSquareOrP.SplitDisj(
				LeftHolds(
					"N(α) = 1 or N(α) = p p would make p divide m − i or m + i",
					Given(func(b *Argument, oneOrSquare Fact) {
						b.Show(
							"neither is possible",
							oneOrSquare.SplitDisj(
								LeftHolds(
									"N(α) = 1 is impossible: then 1 = u p + v (m + i), and p would divide m − i",
									Given(func(c *Argument, one Fact) {
										_, inverse := c.ObtainAs[Complex](
											"α has norm 1, so it is a unit of ℤ[i]: let y be its inverse",
											"∃y:complex. y ∈ gaussian_integers ∧ α * y = &1",
											By(generator[0], one, NormOneUnit.At(alpha), ring_ideal.RingUnitDef.At(gaussianRing, alpha)))
										oneIn := c.Have(
											"so 1 = α y lies in the ideal",
											"complex_of_real(&1) ∈ «Span»",
											BySets(generator[1], inverse))
										singleton := c.Have(
											"m + i alone lies in ℤ[i]",
											"{«m + i»} ⊆ gaussian_integers",
											BySets(muIn))
										u, _, combination := c.Obtain2As[Complex, Complex](
											"the ideal is p ℤ[i] plus the ideal of m + i, so 1 = u p + t",
											"∃u t:complex. u ∈ gaussian_integers ∧ t ∈ «(m + i)» ∧ &1 = u * complex_of_real(&p) + t",
											BySets(
												oneIn,
												singleton,
												ring_ideal.SpanInsert.Read(ring).At(c.TermAs[Set[Complex]]("{«m + i»}"), piIn)))
										bezout := c.Conjuncts(
											combination,
											"u is a Gaussian integer",
											"t lies in the ideal of m + i",
											"1 = u p + t")
										v, multiple := c.ObtainAs[Complex](
											"t is a multiple v (m + i) with v in ℤ[i]",
											"∃v:complex. v ∈ gaussian_integers ∧ t = v * «m + i»",
											BySets(bezout[1], ring_ideal.PrincipalIdealMultiples.Read(ring).At(muIn)))
										cofactor := c.Conjuncts(
											multiple,
											"v is a Gaussian integer",
											"t = v (m + i)")
										_, quotient := c.ObtainAs[Nat](
											"p divides m m + 1 = p c",
											"∃c:num. m * m + 1 = p * c",
											By(divides, nat_divides.DividesFactor.At(p, c.TermAs[Nat]("m * m + 1"))))
										conjugate := c.TermAs[Complex]("«m − i»")
										norm := c.Have(
											"(m + i)(m − i) = m m + 1 = p c",
											"«m + i» * «m − i» = complex_of_real(&p) * complex_of_real(&c)",
											Simp(complex_field.Parts, Fwd(complex_field.ComplexMulDef), Fwd(complex_field.ComplexOfRealDef)),
											ByArith(quotient))
										w, wDef := c.LetAs[Complex]("w", "u * «m − i» + v * complex_of_real(&c)")
										divisible := c.Have(
											"multiplying 1 = u p + v (m + i) by m − i gives m − i = p w",
											"«m − i» = complex_of_real(&p) * w",
											ByArith(
												Scaled(pi, wDef),
												Scaled(conjugate, bezout[2]),
												Scaled(conjugate, cofactor[1]),
												Scaled(v, norm)))
										conjugateIn := c.Have(
											"m − i and c are Gaussian integers",
											"«m − i» ∈ gaussian_integers ∧ complex_of_real(&c) ∈ gaussian_integers",
											By(
												MemberIffIntegerParts,
												complex_field.PartsOfReal,
												int_construction.IntegerOfNum,
												int_construction.IntegerClosedUnderNeg))
										wIn := c.Have(
											"w is a Gaussian integer",
											"w ∈ gaussian_integers",
											By(
												wDef,
												bezout[0],
												cofactor[0],
												conjugateIn,
												GaussianSubring,
												comm_ring.SubringAdd.At(
													complexRing,
													gaussianIntegers,
													c.TermAs[Complex]("u * «m − i»"),
													c.TermAs[Complex]("v * complex_of_real(&c)")),
												comm_ring.SubringMul.At(complexRing, gaussianIntegers, u, conjugate),
												comm_ring.SubringMul.At(
													complexRing, gaussianIntegers, v, c.TermAs[Complex]("complex_of_real(&c)"))))
										pOne := c.Have(
											"a natural number dividing m − i in ℤ[i] is 1",
											"p = 1",
											By(wIn, divisible, MultipleWithUnitImaginaryPart.At(p, m, w)))
										c.Show(
											"but a prime is not 1",
											By(prime, pOne, nat_prime.PrimeDef.At(p)))
									})),
								RightHolds(
									"N(α) = p p is impossible: then β is a unit, and p would divide m + i",
									Given(func(c *Argument, square Fact) {
										betaOne := c.Have(
											"cancelling p p from N(α) N(β) = p p leaves N(β) = 1",
											"gaussian_norm(β) = 1",
											ByArith(
												prime,
												product,
												square,
												nat_arith.MulEqLCancel.At(
													c.TermAs[Nat]("p * p"),
													c.TermAs[Nat]("gaussian_norm(β)"),
													c.TermAs[Nat]("1")),
												nat_arith.MulEqZero.At(p, p),
												nat_prime.PrimeAtLeastTwo.At(p)))
										y, inverse := c.ObtainAs[Complex](
											"β has norm 1, so it is a unit of ℤ[i]: let y be its inverse",
											"∃y:complex. y ∈ gaussian_integers ∧ β * y = &1",
											By(betaFact, betaOne, NormOneUnit.At(beta), ring_ideal.RingUnitDef.At(gaussianRing, beta)))
										gamma, gammaFact := c.ObtainAs[Complex](
											"m + i lies in the ideal, so m + i = α γ with γ in ℤ[i]",
											"∃γ:complex. γ ∈ gaussian_integers ∧ «m + i» = α * γ",
											BySets(generator[1], ring_ideal.SpanContains.At(gaussianRing, generators)))
										factors := c.Conjuncts(
											betaFact,
											"β is a Gaussian integer",
											"p = α β")
										inverses := c.Conjuncts(
											inverse,
											"y is a Gaussian integer",
											"β y = 1")
										multiple := c.Conjuncts(
											gammaFact,
											"γ is a Gaussian integer",
											"m + i = α γ")
										divisible := c.Have(
											"α = α β y = p y, so m + i = p (y γ)",
											"«m + i» = complex_of_real(&p) * (y * γ)",
											ByArith(
												Scaled(c.TermAs[Complex]("y * γ"), factors[1]),
												Scaled(c.TermAs[Complex]("α * γ"), inverses[1]),
												multiple[1]))
										productIn := c.Have(
											"y γ is a Gaussian integer",
											"y * γ ∈ gaussian_integers",
											By(
												inverses[0],
												multiple[0],
												GaussianSubring,
												comm_ring.SubringMul.At(complexRing, gaussianIntegers, y, gamma)))
										c.Show(
											"but a prime is not 1, and no natural number other than 1 divides m + i",
											By(
												prime,
												productIn,
												divisible,
												nat_prime.PrimeDef.At(p),
												MultipleWithUnitImaginaryPart.At(p, m, c.TermAs[Complex]("y * γ"))))
									}))))
					})),
				RightHolds(
					"N(α) = p, and the parts of α give p as a sum of two squares",
					Given(func(b *Argument, isP Fact) {
						integral := b.Have(
							"the parts of α are integers",
							"integer(re(α)) ∧ integer(im(α))",
							By(generator[0], MemberIffIntegerParts.At(alpha)))
						r, rSquare := b.UnpackAs[Nat](
							GroupPremises(integral, int_construction.IntegerSquareNatural.At(b.TermAs[Real]("re(α)"))),
							"r")
						s, sSquare := b.UnpackAs[Nat](
							GroupPremises(integral, int_construction.IntegerSquareNatural.At(b.TermAs[Real]("im(α)"))),
							"s")
						sum := b.Have(
							"read in ℝ, p = N(α) = r r + s s",
							"real_of_num(p) = real_of_num(r) * real_of_num(r) + real_of_num(s) * real_of_num(s)",
							ByArith(isP, rSquare, sSquare, generator[0], NormReal.At(alpha)))
						b.Take(r)
						b.Take(s)
						b.Show(
							"so p = r r + s s in ℕ",
							By(sum, real_construction.OfNumEq, real_construction.OfNumAdd, real_construction.OfNumMul))
					}))))
	}),
})}
