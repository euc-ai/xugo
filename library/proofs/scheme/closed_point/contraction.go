// contraction.go — a maximal ideal of a chart meets the polynomials in the
// chart's coordinate in the multiples of a monic irreducible polynomial's
// value: proved once for a ring k[t] + k[t]·w with w² in k[t] and 1/t
// outside it, and read here at chart one, k[1/x] + k[1/x]·y/x²; its reading
// at chart zero, k[x] + k[x]·y, is MaximalContractsToPrime.

package closed_point

