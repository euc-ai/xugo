// QuadraticChartContractsToPrime — let t be transcendental over a subfield k
// of L and w a member of L with w² in k[t], so that k[t] + k[t]·w is a ring;
// if 1/t lies outside it, a maximal ideal m of it meets k[t] in the ideal
// generated by p(t), p monic and irreducible over k. m holds a nonzero z: t
// itself, or else v·t − 1 for v inverting t modulo m, which is not zero, 1/t
// lying outside the ring. Write z = α + β·w with α and β in k[t]. A vanishing
// conjugate α − β·w makes z = α + α a member of k[t]; otherwise the norm
// (α − β·w)·z = α² − β²·w², a nonzero member of m, is one. So m ∩ k[t], the
// contraction of a prime ideal, is a nonzero prime ideal of k[t], and
// principal_ideal_domain.NonzeroPrimeMonicIrreducible gives its generator.
var QuadraticChartContractsToPrime = quadraticChartContractsToPrimeThm{family.Add(registry.ProofEntry{
	Name: "QuadraticChartContractsToPrime",
	Key:  "prop_3f2785c46e6fcbf1",
	Build: family.Theorem(Statement{
		Binders: "∀L:field_on(A). ∀k:set(A). ∀t w:A. ∀m:set(A).",
		Hypotheses: []string{
			"subfield(L, k)",
			"t ∈ L.carrier",
			"¬algebraic_over(L, k, t)",
			"w ∈ L.carrier",
			"w * w ∈ «polynomials»",
			"L.inv(t) ∉ «chart»",
			"maximal_ideal(restrict_ring(field_ring(L), «chart»), m)",
		},
		Conclusion: "∃p:(num → A). " +
			"    polynomial_irreducible(restrict_ring(field_ring(L), k), p) ∧ " +
			"    polynomial_monic(p) ∧ " +
			"    m ∩ «polynomials» = " +
			"    ideal_span(restrict_ring(field_ring(L), «polynomials»), {polynomial_eval(p, t)})",
		Abbrev: Abbrev{
			{Name: "polynomials", Text: "polynomial_image(field_ring(L), k, t)"},
			{Name: "chart", Text: "{a + b * w | a:A, b:A | a ∈ «polynomials» ∧ b ∈ «polynomials»}"},
		},
	},
		func(
			arg *Argument,
			L field.FieldFact[on.L],
			k *Expr[Set[A]],
			t, w *Expr[A],
			m *Expr[Set[A]],
			subK, tInL, transcendental, wInL, square, inverseOutside, maximal Fact,
		) {
			ring := field.RingOn.Read(L)
			tm := arg.MemberOf[on.L](t, tInL)
			wm := arg.MemberOf[on.L](w, wInL)
			polynomials := arg.TermAs[Set[A]]("«polynomials»")
			chart := arg.TermAs[Set[A]]("«chart»")
			kt := arg.Conjuncts(
				GroupPremises(subK, algebraic_element.PolynomialImageRing.Read(L).At(k, tm)),
				"k[t] is a subring of L",
				"holding k",
				"and t",
				"inside k(t)")
			subringT, tInPolynomials := kt[0], kt[2]
			polynomialsInL := comm_ring.SubringSubset.Read(subringT)
			chartFacts := arg.Conjuncts(
				GroupPremises(subringT, square, fractional_ideal.RingOneAndElement.Read(L).At(polynomials, wm)),
				"the chart k[t] + k[t]·w is a subring of L, w² lying in k[t]",
				"holding k[t]",
				"and w")
			subringChart, polynomialsInChart := chartFacts[0], chartFacts[1]
			chartRing := arg.Have(
				"the chart is a ring on its set",
				"comm_ring_on(restrict_ring(field_ring(L), «chart»))",
				By(subringChart, comm_ring.SubringRingOn.Read(ring).At(chart)))
			mPrime := arg.Have(
				"m is a prime ideal of the chart",
				"prime_ideal(restrict_ring(field_ring(L), «chart»), m)",
				By(maximal, ring_ideal.MaximalIsPrime.Read(chartRing).At(m)))
			mInChart := arg.Have(
				"m lies in the chart",
				"m ⊆ «chart»",
				By(
					maximal,
					ring_ideal.MaximalIdealIdeal,
					ring_ideal.IdealSubset.At(arg.TermAs[RingOps[A]]("restrict_ring(field_ring(L), «chart»)"), m)))
			tInChart := arg.Have(
				"t lies in the chart",
				"t ∈ «chart»",
				BySets(tInPolynomials, polynomialsInChart))
			tNonzero := arg.Have(
				"t is not zero, being transcendental over k",
				"t ≠ L.zero",
				By(subK, transcendental, algebraic_element.TranscendentalInverse.Read(L).At(k, tm)))

			// m is not zero: else t, outside m, would be a unit of the chart.
			z, zFacts := arg.ObtainAs[A](
				"m holds a nonzero member",
				"∃z:A. z ∈ m ∧ z ≠ L.zero",
				Derive(func(b *Argument) {
					b.Cases(b.Term("t ∈ m"))
					b.When(
						"t itself, which is not zero",
						func(c *Argument, tInM Fact) {
							c.Take(t)
							c.Show(
								"t lies in m and is not zero",
								By(tInM, tNonzero))
						})
					b.Otherwise(
						"otherwise v·t − 1 lies in m for some v in the chart, m being maximal",
						func(c *Argument, tOutside Fact) {
							v, vFacts := c.ObtainAs[A](
								"t, outside the maximal ideal m, has an inverse v modulo m",
								"∃v:A. v ∈ «chart» ∧ v * t - L.one ∈ m",
								By(
									maximal,
									tInChart,
									tOutside,
									ring_ideal.MaximalUnitModulo.Read(chartRing).At(m, c.MemberOf[on.Any](t, tInChart))))
							vParts := c.Conjuncts(
								vFacts,
								"v lies in the chart",
								"and v·t − 1 in m")
							vInL := c.Have(
								"v lies in L",
								"v ∈ L.carrier",
								BySets(vParts[0], comm_ring.SubringSubset.Read(subringChart)))
							notInverse := c.Have(
								"v·t ≠ 1, else v = 1/t would lie in the chart",
								"v * t ≠ L.one",
								By(
									inverseOutside,
									tInL,
									vInL,
									vParts[0],
									field.InvLeftUniqueOn.Read(L).At(c.MemberOf[on.L](v, vInL), tm)))
							c.Take(c.TermAs[A]("v * t - L.one"))
							c.Show(
								"v·t − 1 lies in m and is not zero",
								ByArith(L, notInverse, tInL, vInL, vParts[1]))
						})
				}))
			zParts := arg.Conjuncts(
				zFacts,
				"z lies in m",
				"and is not zero")
			zInM, zNonzero := zParts[0], zParts[1]
			zInChart := arg.Have(
				"z lies in the chart",
				"z ∈ «chart»",
				BySets(zInM, mInChart))
			α, β, zCoordinates := arg.Unpack2As[A, A](zInChart, "α", "β")
			coordinates := arg.Conjuncts(
				zCoordinates,
				"α lies in k[t]",
				"so does β",
				"and z = α + β·w")
			αIn, βIn, zValue := coordinates[0], coordinates[1], coordinates[2]
			coordinatesInL := arg.Conjuncts(
				arg.Have(
					"α and β lie in L",
					"α ∈ L.carrier ∧ β ∈ L.carrier",
					BySets(αIn, βIn, polynomialsInL)),
				"α lies in L",
				"β lies in L")

			// m ∩ k[t] is not zero: it holds z, or the norm of z.
			contractionNonzero := arg.Have(
				"m ∩ k[t] is not zero",
				"m ∩ «polynomials» ≠ {L.zero}",
				Derive(func(b *Argument) {
					b.Cases(b.Term("α + -β * w = L.zero"))
					b.When(
						"a vanishing conjugate makes β·w = α, so z = α + α lies in k[t]",
						func(c *Argument, conjugateZero Fact) {
							half := c.Have(
								"β·w = α",
								"β * w = α",
								ByArith(L, conjugateZero, wInL, coordinatesInL[0], coordinatesInL[1]))
							αm := c.MemberOf[on.Any](α, αIn)
							c.Show(
								"z = α + α is a nonzero member of m ∩ k[t]",
								BySets(zNonzero, zValue, half, αIn, zInM, comm_ring.SubringAdd.Read(subringT).At(αm, αm)))
						})
					b.Otherwise(
						"otherwise the norm (α − β·w)·z = α² − β²·w² is a nonzero member of m ∩ k[t]",
						func(c *Argument, conjugateNonzero Fact) {
							conjugate := c.TermAs[A]("α + -β * w")
							conjugateIn := c.Have(
								"the conjugate α − β·w lies in the chart",
								"α + -β * w ∈ «chart»",
								BySets(αIn, βIn, comm_ring.SubringNeg.Read(subringT).At(c.MemberOf[on.Any](β, βIn))))
							inL := c.Conjuncts(
								c.Have(
									"the conjugate and z lie in L",
									"α + -β * w ∈ L.carrier ∧ z ∈ L.carrier",
									By(
										Normalized,
										zValue,
										wInL,
										coordinatesInL[0],
										coordinatesInL[1],
										comm_ring.AddIn.Read(ring),
										comm_ring.MulIn.Read(ring),
										comm_ring.NegIn.Read(ring))),
								"the conjugate lies in L",
								"so does z")
							normValue := c.Have(
								"(α − β·w)·z = α² − β²·w²",
								"(α + -β * w) * z = α * α + -(β * β) * (w * w)",
								ByArith(L, Scaled(conjugate, zValue), wInL, coordinatesInL[0], coordinatesInL[1], inL[0], inL[1]))
							normInPolynomials := c.Have(
								"which lies in k[t], w² lying there",
								"α * α + -(β * β) * (w * w) ∈ «polynomials»",
								By(
									αIn,
									βIn,
									square,
									comm_ring.SubringAdd.Read(subringT),
									comm_ring.SubringMul.Read(subringT),
									comm_ring.SubringNeg.Read(subringT)))
							normInM := c.Have(
								"and in m, z lying there",
								"(α + -β * w) * z ∈ m",
								By(zInM, conjugateIn, ring_ideal.IdealMul.Read(ring_ideal.MaximalIdealIdeal.Read(maximal))))
							c.Show(
								"the norm is not zero, a product of nonzero members of the field L",
								BySets(
									zNonzero,
									conjugateNonzero,
									normValue,
									normInPolynomials,
									normInM,
									inL[0],
									inL[1],
									field.MulEqZeroOn.Read(L).At(c.MemberOf[on.L](conjugate, inL[0]), c.MemberOf[on.L](z, inL[1]))))
						})
				}))

			// m ∩ k[t] is a prime ideal of k[t].
			contractionIdeal := arg.Have(
				"m ∩ k[t] is an ideal of k[t], the contraction of an ideal of the chart",
				"ring_ideal(restrict_ring(field_ring(L), «polynomials»), m ∩ «polynomials»)",
				By(
					subringT,
					polynomialsInChart,
					ring_ideal.MaximalIdealIdeal.Read(maximal),
					ring_ideal.IdealContraction.At(arg.TermAs[RingOps[A]]("field_ring(L)"), polynomials, chart, m),
					set_algebra.InterComm.At(m, polynomials)))
			primeOnPolynomials := arg.Have(
				"a product of members of k[t] lying in m has a factor there, k[t] lying in the chart",
				"∀x y:A. x ∈ «polynomials» ∧ y ∈ «polynomials» ∧ x * y ∈ m ⇒ x ∈ m ∨ y ∈ m",
				By(polynomialsInChart, set_basic.SubsetDef, ring_ideal.PrimeIdealPrime.Read(mPrime)))
			contraction := arg.Have(
				"so m ∩ k[t], proper as m is, is a prime ideal of k[t]",
				"prime_ideal(restrict_ring(field_ring(L), «polynomials»), m ∩ «polynomials»)",
				BySets(
					contractionIdeal,
					primeOnPolynomials,
					ring_ideal.MaximalIdealProper.Read(maximal),
					ring_ideal.PrimeIdealDef))
			arg.Show(
				"a nonzero prime ideal of k[t] is generated by p(t), p monic and irreducible over k",
				By(
					subK,
					tInL,
					transcendental,
					contraction,
					contractionNonzero,
					principal_ideal_domain.NonzeroPrimeMonicIrreducible.Read(L).At(
						k, tm, arg.TermAs[Set[A]]("m ∩ «polynomials»"))))
		}),
})}

// ChartOneContractsToPrime — a maximal ideal m of chart one meets k[s],
// s = 1/x, in the ideal generated by p(s) for p monic and irreducible over
// k. Chart one is k[s] + k[s]·u with u = y/x², whose square
// s(1 + as² + bs³) lies in k[s] (elliptic_curve.WeierstrassChartOneEquation);
// s is transcendental over k as x is, and 1/s = x lies in chart zero but not
// in k, so outside chart one, the two charts meeting in k
// (elliptic_curve.WeierstrassGlobalSections).
var ChartOneContractsToPrime = chartOneContractsToPrimeThm{family.Add(registry.ProofEntry{
	Name: "ChartOneContractsToPrime",
	Key:  "prop_57ce97313165412d",
	Build: family.Theorem(Statement{
		Binders: "∀L:field_on(A). ∀k:set(A). ∀x y a b:A. ∀m:set(A).",
		Hypotheses: []string{
			"weierstrass(L, k, x, y, a, b)",
			"maximal_ideal(restrict_ring(field_ring(L), weierstrass_chart_one(L, k, x, y)), m)",
		},
		Conclusion: "∃p:(num → A). " +
			"    polynomial_irreducible(restrict_ring(field_ring(L), k), p) ∧ " +
			"    polynomial_monic(p) ∧ " +
			"    m ∩ «polynomials» = " +
			"    ideal_span(restrict_ring(field_ring(L), «polynomials»), {polynomial_eval(p, L.inv(x))})",
		Abbrev: Abbrev{
			{Name: "u", Text: "(y * (L.inv(x) * L.inv(x)))"},
			{Name: "polynomials", Text: "polynomial_image(field_ring(L), k, L.inv(x))"},
		},
	},
		func(
			arg *Argument,
			L field.FieldFact[on.L],
			k *Expr[Set[A]],
			x, y, a, b *Expr[A],
			m *Expr[Set[A]],
			datum, maximal Fact,
		) {
			ring := field.RingOn.Read(L)
			// Installed here: two Conjuncts below each group it, and a bare reading installs only once.
			subK := arg.Simplified(elliptic_curve.WeierstrassSubfield.Read(datum).AsFact())
			transcendental := elliptic_curve.WeierstrassTranscendental.Read(datum)
			xm := arg.MemberOf[on.L](x, elliptic_curve.WeierstrassXInField.Read(datum).AsFact())
			ym := arg.MemberOf[on.L](y, elliptic_curve.WeierstrassYInField.Read(datum).AsFact())
			inverse := arg.Conjuncts(
				GroupPremises(subK, transcendental, algebraic_element.TranscendentalInverse.Read(L).At(k, xm)),
				"x is not zero",
				"s = 1/x lies in L",
				"and is transcendental over k")
			s := arg.TermAs[A]("L.inv(x)")
			sm := arg.MemberOf[on.L](s, inverse[1])
			um := comm_ring.MulIn.Read(ring).At(ym, comm_ring.MulIn.Read(ring).At(sm, sm))
			ks := arg.Conjuncts(
				GroupPremises(subK, algebraic_element.PolynomialImageRing.Read(L).At(k, sm)),
				"k[s] is a subring of L",
				"holding k",
				"and s",
				"inside k(s)")
			coefficients := arg.Have(
				"a and b lie in k[s], as k does",
				"a ∈ «polynomials» ∧ b ∈ «polynomials»",
				BySets(
					ks[1],
					elliptic_curve.WeierstrassCoefficientA.Read(datum),
					elliptic_curve.WeierstrassCoefficientB.Read(datum)))
			square := arg.Have(
				"u² = s(1 + as² + bs³) lies in k[s]",
				"«u» * «u» ∈ «polynomials»",
				GroupPremises(datum, elliptic_curve.WeierstrassChartOneEquation.Read(L).At(k, x, y, a, b)).Rw(),
				By(
					ks[2],
					coefficients,
					comm_ring.SubringAdd.Read(ks[0]),
					comm_ring.SubringMul.Read(ks[0]),
					comm_ring.SubringOne.Read(ks[0])))
			xInChartZero := arg.Have(
				"x lies in chart zero, as k[x] does",
				"x ∈ weierstrass_chart_zero(field_ring(L), k, x, y)",
				BySets(
					subK,
					datum,
					elliptic_curve.WeierstrassBasisZero.Read(L).At(k, x, y, a, b),
					algebraic_element.PolynomialImageRing.Read(L).At(k, xm)))
			xNotConstant := arg.Have(
				"x is not a constant, being transcendental over k",
				"x ∉ k",
				By(subK, transcendental, algebraic_element.MemberAlgebraic.Read(L).At(k, x)))
			outside := arg.Have(
				"so 1/s = x lies outside chart one, the two charts meeting in k",
				"L.inv(L.inv(x)) ∉ weierstrass_chart_one(L, k, x, y)",
				BySets(
					xInChartZero,
					xNotConstant,
					datum,
					elliptic_curve.WeierstrassGlobalSections.Read(L).At(k, x, y, a, b),
					field.InvInvOn.Read(L).At(xm)))
			inverseOutside := arg.Unfolded(outside, elliptic_curve.WeierstrassChartOneDef)
			maximalOnChart := arg.Unfolded(maximal, elliptic_curve.WeierstrassChartOneDef)
			arg.Show(
				"chart one is k[s] + k[s]·u, s transcendental and 1/s outside it",
				By(
					subK,
					sm,
					inverse[2],
					um,
					square,
					inverseOutside,
					maximalOnChart,
					QuadraticChartContractsToPrime.Read(L).At(k, sm, um, m)))
		}),
})}
