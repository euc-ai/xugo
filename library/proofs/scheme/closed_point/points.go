// ChartZeroMaximalInvertible — every maximal ideal of chart zero is invertible.
// Chart 0 is the quadratic ring k[x] + k[x]·y, x transcendental over k and
// y² = C(x) for the cubic C = X³ + aX + b; its partials 2y and C′(x) =
// 3x² + a span it (WeierstrassChartPartialsUnit), and a maximal ideal meets
// k[x] in the ideal of p(x) for an irreducible p (MaximalContractsToPrime),
// so QuadraticChartMaximalInvertible applies at t = x, w = y and F = C.
var ChartZeroMaximalInvertible = chartZeroMaximalInvertibleThm{family.Add(registry.ProofEntry{
	Name: "ChartZeroMaximalInvertible",
	Key:  "prop_450f9b9902d7bdba",
	Reading: "k need not be finite. Smoothness, 2 ≠ 0 and 4a³ + 27b² ≠ 0, " +
		"enters only through WeierstrassChartPartialsUnit: it makes 2y and 3x² + " +
		"a span chart zero, the Jacobian pair QuadraticChartMaximalInvertible asks.",
	Build: family.Theorem(Statement{
		Binders: "∀L:field_on(A). ∀k:set(A). ∀x y a b:A. ∀m:set(A).",
		Hypotheses: []string{
			"smooth_weierstrass(L, k, x, y, a, b)",
			"maximal_ideal(restrict_ring(field_ring(L), «curveChart0»), m)",
		},
		Conclusion: "invertible_fractional(field_ring(L), «curveChart0», m)",
		Abbrev: Abbrev{
			{Name: "cubic", Text: "basis_vector(3) + a • basis_vector(1) + b • basis_vector(0)"},
		},
	}, func(
		arg *Argument,
		L field.FieldFact[on.L],
		k *Expr[Set[A]],
		x, y, a, b *Expr[A],
		smooth Fact,
		m *Expr[Set[A]],
		maximal Fact,
	) {
		datum := arg.Simplified(elliptic_curve.SmoothWeierstrassDatum.Read(smooth).AsFact())
		xm := arg.MemberOf[on.L](x, elliptic_curve.WeierstrassXInField.Read(datum).AsFact())
		ym := arg.MemberOf[on.L](y, elliptic_curve.WeierstrassYInField.Read(datum).AsFact())

		// The chart: k[x] + k[x]·y with y² = C(x), its partials 2y and C′(x) spanning it.
		chart := arg.Have(
			"chart zero is k[x] + k[x]·y",
			"«curveChart0» = "+
				"{c + d * y:A | "+
				"    c:A, "+
				"    d:A | "+
				"    c ∈ polynomial_image(field_ring(L), k, x) ∧ d ∈ polynomial_image(field_ring(L), k, x)}",
			Unfold(elliptic_curve.WeierstrassChartZeroDef))
		cubic := arg.Conjuncts(
			GroupPremises(datum, WeierstrassCubicPolynomial.Read(L).At(k, x, y, a, b)),
			"the cubic C = X³ + aX + b is a polynomial over k",
			"y² is its value at x",
			"its derivative takes the value 3x² + a at x")
		jacobian := arg.Have(
			"2y and C′(x) = 3x² + a span chart zero",
			"ideal_span(restrict_ring(field_ring(L), «curveChart0»), "+
				"    {y + y, polynomial_eval(polynomial_derivative(«cubic»), x)}) = "+
				"«curveChart0»",
			By(smooth, cubic[2], elliptic_curve.WeierstrassChartPartialsUnit.Read(L).At(k, x, y, a, b)))

		// m lies over an irreducible p of k[x].
		p, contracted := arg.UnpackAs[Fun[Nat, A]](
			GroupPremises(datum, maximal, MaximalContractsToPrime.Read(L).At(k, x, y, a, b, m)),
			"p")
		parts := arg.Conjuncts(
			contracted,
			"p is irreducible over k",
			"and monic",
			"m meets k[x] in p(x)·k[x]")
		arg.Show(
			"a maximal ideal of the quadratic ring k[x] + k[x]·y is invertible, its Jacobian pair spanning it",
			By(
				elliptic_curve.WeierstrassSubfield.Read(datum),
				xm,
				elliptic_curve.WeierstrassTranscendental.Read(datum),
				ym,
				cubic[0],
				cubic[1],
				chart,
				jacobian,
				maximal,
				parts[0],
				parts[2],
				QuadraticChartMaximalInvertible.Read(L).At(
					k,
					arg.TermAs[Set[A]]("«curveChart0»"),
					xm,
					ym,
					arg.TermAs[Fun[Nat, A]]("«cubic»"),
					m,
					p)))
	}),
})}

