// MaximalContractsToPrime — an affine maximal ideal m meets k[x] in the ideal
// generated by p(x) for a monic irreducible polynomial p over k. Chart zero
// is k[x] + k[x]·y with y² = x³ + ax + b in k[x] and x transcendental over
// k; 1/x lies in chart one, by its basis, and not in k, being transcendental,
// so outside chart zero, the two charts meeting in k. The general contraction
// QuadraticChartContractsToPrime then applies at t = x, w = y.
var MaximalContractsToPrime = maximalContractsToPrimeThm{family.Add(registry.ProofEntry{
	Name: "MaximalContractsToPrime",
	Key:  "prop_6cc09c5b3eff85c7",
	Reading: "Neither k finite, 2 ≠ 0 nor the discriminant is asked: any " +
		"Weierstrass datum. What is load-bearing is that 1/x lies outside chart zero.",
	Build: family.Theorem(Statement{
		Binders: "∀L:field_on(A). ∀k:set(A). ∀x y a b:A. ∀m:set(A).",
		Hypotheses: []string{
			"weierstrass(L, k, x, y, a, b)",
			"maximal_ideal(restrict_ring(field_ring(L), weierstrass_chart_zero(field_ring(L), k, x, y)), m)",
		},
		Conclusion: "∃p:(num → A). " +
			"    polynomial_irreducible(restrict_ring(field_ring(L), k), p) ∧ " +
			"    polynomial_monic(p) ∧ " +
			"    m ∩ «polynomials» = " +
			"    ideal_span(restrict_ring(field_ring(L), «polynomials»), {polynomial_eval(p, x)})",
		Abbrev: Abbrev{
			{Name: "polynomials", Text: "polynomial_image(field_ring(L), k, x)"},
		},
	},
		func(
			arg *Argument,
			L field.FieldFact[on.L],
			k *Expr[Set[A]],
			x, y, a, b *Expr[A],
			m *Expr[Set[A]],
			datum, maximal Fact,
		) {
			// Installed here: two Conjuncts below each group it, and a bare reading installs only once.
			subK := arg.Simplified(elliptic_curve.WeierstrassSubfield.Read(datum).AsFact())
			transcendental := elliptic_curve.WeierstrassTranscendental.Read(datum)
			xm := arg.MemberOf[on.L](x, elliptic_curve.WeierstrassXInField.Read(datum).AsFact())
			ym := arg.MemberOf[on.L](y, elliptic_curve.WeierstrassYInField.Read(datum).AsFact())
			kx := arg.Conjuncts(
				GroupPremises(subK, algebraic_element.PolynomialImageRing.Read(L).At(k, xm)),
				"k[x] is a subring of L",
				"holding k",
				"and x",
				"inside k(x)")
			coefficients := arg.Have(
				"a and b lie in k[x], as k does",
				"a ∈ «polynomials» ∧ b ∈ «polynomials»",
				BySets(
					kx[1],
					elliptic_curve.WeierstrassCoefficientA.Read(datum),
					elliptic_curve.WeierstrassCoefficientB.Read(datum)))
			square := arg.Have(
				"y² = x³ + ax + b lies in k[x]",
				"y * y ∈ «polynomials»",
				elliptic_curve.WeierstrassEquation.Read(datum).AsFact().Rw(),
				By(kx[2], coefficients, comm_ring.SubringAdd.Read(kx[0]), comm_ring.SubringMul.Read(kx[0])))
			inverse := arg.Conjuncts(
				GroupPremises(subK, transcendental, algebraic_element.TranscendentalInverse.Read(L).At(k, xm)),
				"x is not zero",
				"1/x lies in L",
				"and is transcendental over k")
			s := arg.TermAs[A]("L.inv(x)")
			inChartOne := arg.Have(
				"1/x lies in chart one, as k[1/x] does",
				"L.inv(x) ∈ weierstrass_chart_one(L, k, x, y)",
				BySets(
					subK,
					datum,
					elliptic_curve.WeierstrassBasisOne.Read(L).At(k, x, y, a, b),
					algebraic_element.PolynomialImageRing.Read(L).At(k, arg.MemberOf[on.L](s, inverse[1]))))
			outside := arg.Have(
				"so 1/x, not a constant as it is transcendental, "+
					"lies outside chart zero, the two charts meeting in k",
				"L.inv(x) ∉ weierstrass_chart_zero(field_ring(L), k, x, y)",
				BySets(
					inChartOne,
					subK,
					inverse[2],
					datum,
					elliptic_curve.WeierstrassGlobalSections.Read(L).At(k, x, y, a, b),
					algebraic_element.MemberAlgebraic.Read(L).At(k, s)))
			inverseOutside := arg.Unfolded(outside, elliptic_curve.WeierstrassChartZeroDef)
			maximalOnChart := arg.Unfolded(maximal, elliptic_curve.WeierstrassChartZeroDef)
			arg.Show(
				"chart zero is k[x] + k[x]·y, x transcendental and 1/x outside it",
				By(
					subK,
					xm,
					transcendental,
					ym,
					square,
					inverseOutside,
					maximalOnChart,
					QuadraticChartContractsToPrime.Read(L).At(k, xm, ym, m)))
		}),
})}

// MaximalIdealClassification — an affine maximal ideal of a Weierstrass
// curve is (p(x), y − r(x)) for a monic irreducible p and a square root r
// of y² modulo p of degree below p's, or the inert p(x)·A₀ where y² has no
// such root: the classification of a quadratic ring at chart zero,
// k[x] + k[x]·y with y² = x³ + ax + b in k[x], over the prime p(x)·k[x]
// the ideal contracts to (MaximalContractsToPrime).
var MaximalIdealClassification = maximalIdealClassificationThm{family.Add(registry.ProofEntry{
	Name: "MaximalIdealClassification",
	Key:  "prop_e1ce40023419ee37",
	Reading: "A zero quadratic residue gives a ramified first-kind ideal. A " +
		"nonsquare gives the inert ideal (p), whose residue degree is twice deg p.",
	Build: family.Theorem(Statement{
		Binders: "∀L:field_on(A). ∀k:set(A). ∀x y a b:A. ∀m:set(A).",
		Hypotheses: []string{
			"weierstrass(L, k, x, y, a, b)",
			"maximal_ideal(«chartZeroRing», m)",
		},
		Conclusion: "∃p:(num → A). " +
			"    polynomial_irreducible(restrict_ring(field_ring(L), k), p) ∧ " +
			"    polynomial_monic(p) ∧ " +
			"    ((∃r:(num → A). " +
			"            polynomial_over(k, r) ∧ " +
			"            polynomial_degree(r) < polynomial_degree(p) ∧ " +
			"            y * y - polynomial_eval(r, x) * polynomial_eval(r, x) ∈ «pIdeal»(p) ∧ " +
			"            m = " +
			"            ideal_span(«chartZeroRing», {polynomial_eval(p, x), y - polynomial_eval(r, x)})) ∨ " +
			"        (m = ideal_span(«chartZeroRing», {polynomial_eval(p, x)}) ∧ " +
			"            ¬∃r:(num → A). " +
			"                polynomial_over(k, r) ∧ " +
			"                y * y - polynomial_eval(r, x) * polynomial_eval(r, x) ∈ «pIdeal»(p)))",
		Abbrev: Abbrev{
			{Name: "polynomials", Text: "polynomial_image(field_ring(L), k, x)"},
			{Name: "pIdeal", Text: "λp:(num → A). " +
				"    ideal_span(restrict_ring(field_ring(L), «polynomials»), {polynomial_eval(p, x)})"},
			{Name: "chartZeroRing", Text: "restrict_ring(field_ring(L), «curveChart0»)"},
		},
	},
		func(
			arg *Argument,
			L field.FieldFact[on.L],
			k *Expr[Set[A]],
			x, y, a, b *Expr[A],
			m *Expr[Set[A]],
			datum, maximal Fact,
		) {
			kSubfield := elliptic_curve.WeierstrassSubfield.Read(datum)
			xm := arg.MemberOf[on.L](x, elliptic_curve.WeierstrassXInField.Read(datum).AsFact())
			ym := arg.MemberOf[on.L](y, elliptic_curve.WeierstrassYInField.Read(datum).AsFact())

			kx := arg.Conjuncts(
				GroupPremises(kSubfield, algebraic_element.PolynomialImageRing.Read(L).At(k, xm)),
				"k[x] is a subring of L",
				"holding k",
				"and x",
				"inside k(x)")
			coefficients := arg.Have(
				"a and b lie in k[x], as k does",
				"a ∈ «polynomials» ∧ b ∈ «polynomials»",
				BySets(
					kx[1],
					elliptic_curve.WeierstrassCoefficientA.Read(datum),
					elliptic_curve.WeierstrassCoefficientB.Read(datum)))
			square := arg.Have(
				"y² = x³ + ax + b lies in k[x], as x, a and b do",
				"y * y ∈ «polynomials»",
				elliptic_curve.WeierstrassEquation.Read(datum).AsFact().Rw(),
				By(kx[2], coefficients, comm_ring.SubringAdd.Read(kx[0]), comm_ring.SubringMul.Read(kx[0])))
			chart := arg.Have(
				"chart zero is k[x] + k[x]·y",
				"weierstrass_chart_zero(field_ring(L), k, x, y) = "+
					"{c + d * y:A | c:A, d:A | c ∈ «polynomials» ∧ d ∈ «polynomials»}",
				Unfold(elliptic_curve.WeierstrassChartZeroDef))

			p, contracted := arg.UnpackAs[Fun[Nat, A]](
				GroupPremises(datum, maximal, MaximalContractsToPrime.Read(L).At(k, x, y, a, b, m)),
				"p")
			parts := arg.Conjuncts(
				contracted,
				"p is irreducible over k",
				"and monic",
				"m meets k[x] in p(x)·k[x]")
			arg.Take(p)
			arg.Show(
				"p classifies m, by the classification of the quadratic ring k[x] + k[x]·y",
				By(
					parts[0],
					parts[1],
					kSubfield,
					xm,
					ym,
					square,
					chart,
					maximal,
					parts[2],
					QuadraticMaximalIdealClassification.Read(L).At(
						k, arg.TermAs[Set[A]]("weierstrass_chart_zero(field_ring(L), k, x, y)"), xm, ym, m, p)))
		}),
})}

