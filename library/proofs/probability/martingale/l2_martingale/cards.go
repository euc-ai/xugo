var L2BoundedMartingaleConverges = l2BoundedMartingaleConvergesThm{family.Add(registry.ProofEntry{
	Name: "L2BoundedMartingaleConverges",
	Deps: []registry.EntryLike{
		MartingaleEnergy,
		MartingaleIncrementOrthogonal,
		lp_space.FastCauchyLimit,
		lp_space.LpNested,
		event_integral.EventIntegralL1Limit,
		martingale.MartingaleConditional,
		sigma_algebra.GeneratedSigmaAlgebra,
		sigma_algebra.GeneratedSigmaLeast,
		filtration.FiltrationMono,
	},
	Key: "prop_1a8b742902f727f",
	Reading: "The measurable representative is for sigma(union F(n)), not merely the ambient " +
		"sigma algebra. The theorem asserts L2 convergence only; almost sure convergence would " +
		"require additional maximal-inequality arguments. Finiteness of μ makes the L2 limit " +
		"integrable, as the is_cond_exp clause requires. The limit is measurable for the sigma " +
		"algebra generated by the filtration, which lies inside S and need not equal it.",
	Build: family.Card(Statement{
		Binders: "∀Ω:set(A). " +
			"∀S:set(set(A)). " +
			"∀μ:(set(A) → extended_nonneg_real). " +
			"∀F:(num → set(set(A))). " +
			"∀M:(num → A → real).",
		Hypotheses: []string{
			"finite_measure_on(Ω, S, μ)",
			"l2_martingale_on(Ω, S, μ, F, M)",
			"∃C:real. ∀n:num. expectation(Ω, S, μ, λx:A. M(n, x) * M(n, x)) ≤ C",
		},
		Conclusion: "∃Y:(A → real). " +
			"    real_measurable(Ω, filtration_limit_sigma(Ω, F), Y) ∧ " +
			"    real_integrable(Ω, S, μ, λx:A. Y(x) * Y(x)) ∧ " +
			"    real_converges_to(λn:num. expectation(Ω, S, μ, λx:A. (M(n, x) - Y(x)) * (M(n, x) - Y(x))), " +
			"        &0) ∧ " +
			"    (∀n:num. is_cond_exp(Ω, S, μ, F(n), Y, M(n)))",
	},
		"Bounded energies make the sum of squared increment norms convergent, hence "+
			"the classes are L2-Cauchy. FastCauchyLimit with the generated filtration "+
			"sigma algebra gives a measurable representative of the limit; L2-to-L1 "+
			"convergence passes every fixed event-integral identity to that limit."),
})}

