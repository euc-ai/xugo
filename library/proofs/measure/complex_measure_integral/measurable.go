// ComplexMeasurableAdd — the sum of two measurable complex functions is
// measurable: its parts are the sums of their parts.
var ComplexMeasurableAdd = complexMeasurableAddThm{family.Add(registry.ProofEntry{
	Name: "ComplexMeasurableAdd",
	Key:  "prop_1719ff2786e04b55",
	Reading: "The sigma algebra hypothesis is load-bearing. On Ω = {1, 2, 3, 4}, let S be " +
		"the union of the sigma algebras generated by the indicators of {1, 2} and of {1, 3}: " +
		"both indicators are measurable, and their sum exceeds 3/2 only at 1, while {1} ∉ S.",
	Build: family.Theorem(Statement{
		Binders: "∀Ω:set(A). ∀S:set(set(A)). ∀f g:(A → complex).",
		Hypotheses: []string{
			"sigma_algebra_on(Ω, S)",
			"complex_measurable(Ω, S, f)",
			"complex_measurable(Ω, S, g)",
		},
		Conclusion: "complex_measurable(Ω, S, λx:A. f(x) + g(x))",
	}, func(
		a *Argument,
		Ω *Expr[Set[A]],
		S *Expr[Set[Set[A]]],
		f, g *Arrow[A, Complex],
		sigma, fMeasurable, gMeasurable Fact,
	) {
		fParts := a.Unfolded(fMeasurable, ComplexMeasurableDef)
		gParts := a.Unfolded(gMeasurable, ComplexMeasurableDef)
		a.Show(
			"the parts of f + g are the sums of the parts of f and g",
			Simp(Fwd(ComplexMeasurableDef), Fwd(complex_field.PartsAdd)),
			By(
				sigma,
				fParts,
				gParts,
				measurable_function.RealMeasurableAdd.At(
					Ω,
					S,
					a.TermAs[Fun[A, Real]]("λx:A. re(f(x))"),
					a.TermAs[Fun[A, Real]]("λx:A. re(g(x))")),
				measurable_function.RealMeasurableAdd.At(
					Ω,
					S,
					a.TermAs[Fun[A, Real]]("λx:A. im(f(x))"),
					a.TermAs[Fun[A, Real]]("λx:A. im(g(x))"))))
	}),
})}

// ComplexMeasurableMul — the product of two measurable complex functions is
// measurable: its real part re(f)·re(g) − im(f)·im(g) and its imaginary part
// re(f)·im(g) + im(f)·re(g) are built from the parts by real products, sums
// and a negative.
var ComplexMeasurableMul = complexMeasurableMulThm{family.Add(registry.ProofEntry{
	Name: "ComplexMeasurableMul",
	Key:  "prop_2f72fb4096668893",
	Reading: "The sigma algebra hypothesis is load-bearing. On Ω = {1, 2, 3, 4}, let S be the " +
		"union of the sigma algebras generated by the indicators of {1, 2} and of {1, 3}, and let " +
		"f have the first as real part and the second as imaginary part: f is measurable, and the " +
		"real part of f · f, re(f)² − im(f)², exceeds 1/2 only at 2, while {2} ∉ S.",
	Build: family.Theorem(Statement{
		Binders: "∀Ω:set(A). ∀S:set(set(A)). ∀f g:(A → complex).",
		Hypotheses: []string{
			"sigma_algebra_on(Ω, S)",
			"complex_measurable(Ω, S, f)",
			"complex_measurable(Ω, S, g)",
		},
		Conclusion: "complex_measurable(Ω, S, λx:A. f(x) * g(x))",
	}, func(
		a *Argument,
		Ω *Expr[Set[A]],
		S *Expr[Set[Set[A]]],
		f, g *Arrow[A, Complex],
		sigma, fMeasurable, gMeasurable Fact,
	) {
		fParts := a.Unfolded(fMeasurable, ComplexMeasurableDef)
		gParts := a.Unfolded(gMeasurable, ComplexMeasurableDef)
		reF := a.TermAs[Fun[A, Real]]("λx:A. re(f(x))")
		imF := a.TermAs[Fun[A, Real]]("λx:A. im(f(x))")
		reG := a.TermAs[Fun[A, Real]]("λx:A. re(g(x))")
		imG := a.TermAs[Fun[A, Real]]("λx:A. im(g(x))")
		a.Show(
			"the parts of f · g are sums of products of parts, one of them negated",
			Simp(Fwd(ComplexMeasurableDef), Fwd(complex_field.PartsMul), Fwd(real_ring.RealSubDef)),
			By(
				sigma,
				fParts,
				gParts,
				measurable_function.RealMeasurableMul.At(Ω, S, reF, reG),
				measurable_function.RealMeasurableMul.At(Ω, S, imF, imG),
				measurable_function.RealMeasurableNeg.At(Ω, S, a.TermAs[Fun[A, Real]]("λx:A. im(f(x)) * im(g(x))")),
				measurable_function.RealMeasurableAdd.At(
					Ω,
					S,
					a.TermAs[Fun[A, Real]]("λx:A. re(f(x)) * re(g(x))"),
					a.TermAs[Fun[A, Real]]("λx:A. -(im(f(x)) * im(g(x)))")),
				measurable_function.RealMeasurableMul.At(Ω, S, reF, imG),
				measurable_function.RealMeasurableMul.At(Ω, S, imF, reG),
				measurable_function.RealMeasurableAdd.At(
					Ω,
					S,
					a.TermAs[Fun[A, Real]]("λx:A. re(f(x)) * im(g(x))"),
					a.TermAs[Fun[A, Real]]("λx:A. im(f(x)) * re(g(x))"))))
	}),
})}

// ComplexMeasurableScale — a constant multiple of a measurable complex
// function is measurable: it is the product of f with the constant function,
// whose parts are constants.
var ComplexMeasurableScale = complexMeasurableScaleThm{family.Add(registry.ProofEntry{
	Name: "ComplexMeasurableScale",
	Key:  "prop_5885f92b05ce5c15",
	Reading: "The sigma algebra hypothesis is load-bearing. On Ω = {1, 2, 3, 4}, let S be the " +
		"union of the sigma algebras generated by the indicators of {1, 2} and of {1, 3}, and let " +
		"f have the first as real part and the second as imaginary part: f is measurable, and the " +
		"real part of (1 + i) · f, re(f) − im(f), exceeds 1/2 only at 2, while {2} ∉ S.",
	Build: family.Theorem(Statement{
		Binders: "∀Ω:set(A). ∀S:set(set(A)). ∀f:(A → complex). ∀c:complex.",
		Hypotheses: []string{
			"sigma_algebra_on(Ω, S)",
			"complex_measurable(Ω, S, f)",
		},
		Conclusion: "complex_measurable(Ω, S, λx:A. c * f(x))",
	}, func(
		a *Argument,
		Ω *Expr[Set[A]],
		S *Expr[Set[Set[A]]],
		f *Arrow[A, Complex],
		c *Expr[Complex],
		sigma, measurable Fact,
	) {
		constant := a.Have(
			"the constant c is measurable, its parts being constants",
			"complex_measurable(Ω, S, λx:A. c)",
			Simp(Fwd(ComplexMeasurableDef)),
			By(
				sigma,
				measurable_function.RealMeasurableConst.At(Ω, S, a.TermAs[Real]("re(c)")),
				measurable_function.RealMeasurableConst.At(Ω, S, a.TermAs[Real]("im(c)"))))
		a.Show(
			"so c · f, the product of the constant c with f, is measurable",
			By(
				sigma,
				constant,
				measurable,
				ComplexMeasurableMul.At(Ω, S, a.TermAs[Fun[A, Complex]]("λx:A. c"), f)))
	}),
})}

// ComplexMeasurableConj — the conjugate of a measurable complex function is
// measurable: it keeps the real part and negates the imaginary part.
var ComplexMeasurableConj = complexMeasurableConjThm{family.Add(registry.ProofEntry{
	Name: "ComplexMeasurableConj",
	Key:  "prop_2b95fa6704db6d94",
	Reading: "The sigma algebra hypothesis is read only by the law that " +
		"negates the imaginary part, which asks it. The conjugate alone " +
		"would hold without it, negation carrying Borel sets to Borel sets.",
	Build: family.Theorem(Statement{
		Binders: "∀Ω:set(A). ∀S:set(set(A)). ∀f:(A → complex).",
		Hypotheses: []string{
			"sigma_algebra_on(Ω, S)",
			"complex_measurable(Ω, S, f)",
		},
		Conclusion: "complex_measurable(Ω, S, λx:A. conj(f(x)))",
	}, func(
		a *Argument,
		Ω *Expr[Set[A]],
		S *Expr[Set[Set[A]]],
		f *Arrow[A, Complex],
		sigma, measurable Fact,
	) {
		a.Show(
			"conjugation keeps the real part and negates the imaginary part",
			Simp(Fwd(ComplexMeasurableDef), Fwd(complex_field.PartsConj)),
			By(
				sigma,
				a.Unfolded(measurable, ComplexMeasurableDef),
				measurable_function.RealMeasurableNeg.At(Ω, S, a.TermAs[Fun[A, Real]]("λx:A. im(f(x))"))))
	}),
})}

// ComplexMeasurableAbs — the modulus of a measurable complex function is a
// measurable real function. Being nonnegative, it is decided by its rays at
// levels t ≥ 0, and |f| exceeds such a t exactly where re(f)² + im(f)²
// exceeds t², a ray of a measurable function.
var ComplexMeasurableAbs = complexMeasurableAbsThm{family.Add(registry.ProofEntry{
	Name: "ComplexMeasurableAbs",
	Key:  "prop_3b577c0cf002db8d",
	Reading: "The sigma algebra hypothesis is load-bearing. On Ω = {1, 2, 3, 4}, " +
		"let S be the union of the sigma algebras generated by the indicators of {1, " +
		"2} and of {1, 3}, and let f have the first as real part and the second as " +
		"imaginary part: f is measurable, and |f| exceeds 1 only at 1, while {1} ∉ S.",
	Build: family.Theorem(Statement{
		Binders: "∀Ω:set(A). ∀S:set(set(A)). ∀f:(A → complex).",
		Hypotheses: []string{
			"sigma_algebra_on(Ω, S)",
			"complex_measurable(Ω, S, f)",
		},
		Conclusion: "real_measurable(Ω, S, λx:A. |f(x)|)",
	}, func(
		a *Argument,
		Ω *Expr[Set[A]],
		S *Expr[Set[Set[A]]],
		f *Arrow[A, Complex],
		sigma, measurable Fact,
	) {
		reF := a.TermAs[Fun[A, Real]]("λx:A. re(f(x))")
		imF := a.TermAs[Fun[A, Real]]("λx:A. im(f(x))")
		squared := a.Have(
			"re(f)² + im(f)² is measurable, so each of its upper rays is",
			"∀t:real. {x:A | x ∈ Ω ∧ t < re(f(x)) * re(f(x)) + im(f(x)) * im(f(x))} ∈ S",
			By(
				sigma,
				a.Unfolded(measurable, ComplexMeasurableDef),
				measurable_function.RealMeasurableSquare.At(Ω, S, reF),
				measurable_function.RealMeasurableSquare.At(Ω, S, imF),
				measurable_function.RealMeasurableAdd.At(
					Ω,
					S,
					a.TermAs[Fun[A, Real]]("λx:A. re(f(x)) * re(f(x))"),
					a.TermAs[Fun[A, Real]]("λx:A. im(f(x)) * im(f(x))")),
				measurable_function.RealMeasurableIffRay.At(
					Ω,
					S,
					a.TermAs[Fun[A, Real]]("λx:A. re(f(x)) * re(f(x)) + im(f(x)) * im(f(x))"))))
		rays := a.Have(
			"every upper ray of |f| at a level t ≥ 0 is measurable",
			"∀t:real. &0 ≤ t ⇒ {x:A | x ∈ Ω ∧ t < |f(x)|} ∈ S",
			Derive(func(b *Argument) {
				b.FixAs[Real]("t")
				nonneg := b.Assume()
				pointwise := b.Have(
					"nonnegative numbers compare as their squares, |f(x)|² being re(f(x))² + im(f(x))²",
					"∀x:A. t < |f(x)| ⇔ t * t < re(f(x)) * re(f(x)) + im(f(x)) * im(f(x))",
					b.ForEach(func(x *Expr[A]) Action {
						return ByArith(nonneg, complex_abs.AbsSquare.At(f.Apply(x)))
					}))
				b.Show(
					"so the ray of |f| at t is the ray of re(f)² + im(f)² at t², which is measurable",
					By(pointwise, squared.At(b.TermAs[Real]("t * t"))))
			}))
		a.Show(
			"a modulus is nonnegative, so its rays at levels t ≥ 0 decide its measurability",
			By(
				sigma,
				rays,
				complex_abs.AbsNonneg,
				measurable_function.RealMeasurableIffNonnegRay.At(Ω, S, a.TermAs[Fun[A, Real]]("λx:A. |f(x)|"))))
	}),
})}
