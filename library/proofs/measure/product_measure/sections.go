// ProductSectionMeasurable — a section is an inverse image under the map
// fixing the first coordinate. On a generating rectangle the inverse
// image is its second factor or the empty set.
var ProductSectionMeasurable = productSectionMeasurableThm{family.Add(registry.ProofEntry{
	Name: "ProductSectionMeasurable",
	Key:  "prop_18c25c626cb236bf",
	Reading: "No measure enters. A point x off Ω has the empty " +
		"section, since a set of the product σ-algebra lies in Ω × V.",
	Build: family.Theorem(Statement{
		Binders: "∀Ω:set(A). ∀S:set(set(A)). ∀V:set(B). ∀T:set(set(B)). ∀E:set(prod(A, B)). ∀x:A.",
		Hypotheses: []string{
			"S ⊆ {s:set(A) | s ⊆ Ω}",
			"sigma_algebra_on(V, T)",
			"E ∈ product_sigma(Ω, S, V, T)",
		},
		Conclusion: "{y:B | (x, y) ∈ E} ∈ T",
	}, func(
		a *Argument, Ω *Expr[Set[A]], S *Expr[Set[Set[A]]], V *Expr[Set[B]], T *Expr[Set[Set[B]]],
		E *Expr[Set[Prod[A, B]]], x *Expr[A], insideΩ, sigmaT, event Fact,
	) {
		factors := a.Have(
			"measurable factors lie in their carriers and T contains the empty set",
			"S ⊆ {s:set(A) | s ⊆ Ω} ∧ T ⊆ {t:set(B) | t ⊆ V} ∧ ∅ ∈ T",
			By(
				insideΩ,
				sigmaT,
				sigma_algebra.SigmaAlgebraOnDef.At(V, T),
				sigma_algebra.SigmaFiniteOperations.At(V, T)))
		C, cDef := a.LetAs[Set[Set[Prod[A, B]]]](
			"C", "{set_cross(s, t):set(prod(A, B)) | s:set(A), t:set(B) | s ∈ S ∧ t ∈ T}")
		carrier := a.TermAs[Set[Prod[A, B]]]("set_cross(Ω, V)")
		generatorsInside := a.Have(
			"the measurable rectangles lie in the product carrier",
			"C ⊆ {R:set(prod(A, B)) | R ⊆ set_cross(Ω, V)}",
			Simp(Fwd(set_basic.SubsetDef.Inst[Set[Prod[A, B]]]())),
			Derive(func(b *Argument) {
				b.FixAs[Set[Prod[A, B]]]()
				member := b.Assume()
				s, t, rectangle := b.Unpack2As[Set[A], Set[B]](b.Simplified(member, Fwd(cDef)), "s", "t")
				b.Show(
					"each factor lies in its carrier",
					BySets(rectangle, factors, set_product.CrossSubsetIff.At(s, Ω, t, V)))
			}))
		generated := a.TermAs[Set[Set[Prod[A, B]]]]("generated_sigma(set_cross(Ω, V), C)")
		generatedEvent := a.Have(
			"the product event belongs to the generated sigma algebra and lies in its carrier",
			"E ∈ generated_sigma(set_cross(Ω, V), C) ∧ E ⊆ set_cross(Ω, V)",
			Derive(func(b *Argument) {
				member := b.Have(
					"the product sigma algebra is generated by the measurable rectangles",
					"E ∈ generated_sigma(set_cross(Ω, V), C)",
					By(cDef, event, measurable_space.ProductSigmaDef.At(Ω, S, V, T)))
				b.Show(
					"the generated sets lie in the product carrier",
					BySets(
						member,
						generatorsInside,
						sigma_algebra.GeneratedSigmaAlgebra.At(carrier, C),
						sigma_algebra.SigmaAlgebraOnDef.At(carrier, generated)))
			}))
		cross := set_product.InCross.Inst(TypeBinder.BindA[A](), TypeBinder.BindB[B]())
		a.Cases(a.Term("x ∈ Ω"))
		a.When(
			"fix a first coordinate in the carrier",
			func(b *Argument, inside Fact) {
				pair := b.TermAs[Fun[B, Prod[A, B]]]("λy:B. (x, y)")
				into := b.Have(
					"the section map sends V into the product carrier",
					"image(λy:B. (x, y), V) ⊆ set_cross(Ω, V)",
					BySets(inside, cross))
				pullbacks := b.Have(
					"the section map has measurable preimages of the generating rectangles",
					"∀R:set(prod(A, B)). R ∈ C ⇒ preimage_on(V, λy:B. (x, y), R) ∈ T",
					Derive(func(d *Argument) {
						d.FixAs[Set[Prod[A, B]]]()
						member := d.Assume()
						_, _, rectangle := d.Unpack2As[Set[A], Set[B]](d.Simplified(member, Fwd(cDef)), "s", "t")
						preimage := d.Have(
							"the preimage is the second factor when x lies in the first, and is empty otherwise",
							"preimage_on(V, λy:B. (x, y), R) = COND(x ∈ s, t, ∅)",
							BySets(rectangle, factors, cross))
						d.Show(
							"both values of the preimage are measurable",
							By(preimage, rectangle, factors))
					}))
				section := b.Have(
					"the section equals the preimage since the event lies in the product carrier",
					"{y:B | (x, y) ∈ E} = preimage_on(V, λy:B. (x, y), E)",
					BySets(generatedEvent, cross))
				measurableMap := b.Have(
					"the section map is measurable into the generated sigma algebra",
					"measurable_map(V, T, set_cross(Ω, V), generated_sigma(set_cross(Ω, V), C), λy:B. (x, y))",
					By(
						sigmaT,
						generatorsInside,
						into,
						pullbacks,
						measurable_space.MeasurableGenerated.At(V, T, carrier, C, pair)))
				b.Show(
					"E pulls back into T, and its pullback is the section",
					By(
						measurableMap,
						generatedEvent,
						section,
						measurable_space.MeasurableMapDef.At(V, T, carrier, generated, pair)))
			})
		a.Otherwise(
			"a first coordinate outside the carrier has an empty section",
			func(b *Argument, outside Fact) {
				empty := b.Have(
					"no pair with first coordinate x lies in the event",
					"{y:B | (x, y) ∈ E} = ∅",
					BySets(outside, generatedEvent, cross))
				b.Show(
					"the empty set is measurable",
					By(empty, factors))
			})
	}),
})}

// ProductSectionMassMeasurable — the section mass of a product event is
// measurable in the first coordinate. For a finite second measure, the
// product events with measurable real section masses contain the
// rectangles and are closed under complements, by subtracting finite
// masses, and under countable disjoint unions; this λ-system contains the
// product σ-algebra by sigma_algebra.PiLambda. Finite restrictions to an
// increasing cover then exhaust a σ-finite second measure.
var ProductSectionMassMeasurable = productSectionMassMeasurableThm{family.Add(registry.ProofEntry{
	Name: "ProductSectionMassMeasurable",
	Key:  "prop_e4b5964860bb7d8c",
	Reading: "Only the second factor carries a measure. Its σ-finiteness is what the " +
		"measurability of x ↦ ν(E_x) rests on for a general E; on a rectangle it holds without it.",
	Build: family.Sections(Statement{
		Binders: "∀Ω:set(A). " +
			"∀S:set(set(A)). " +
			"∀V:set(B). " +
			"∀T:set(set(B)). " +
			"∀ν:(set(B) → extended_nonneg_real). " +
			"∀E:set(prod(A, B)).",
		Hypotheses: []string{
			"sigma_algebra_on(Ω, S)",
			"sigma_finite_on(V, T, ν)",
			"E ∈ product_sigma(Ω, S, V, T)",
		},
		Conclusion: "extended_measurable(Ω, S, λx:A. ν({y:B | (x, y) ∈ E}))",
		Abbrev: Abbrev{
			{Name: "section", Text: "λE:set(prod(A, B)). λx:A. {y:B | (x, y) ∈ E}"},
			{Name: "realSectionMass", Text: "λν:(set(B) → extended_nonneg_real). λE:set(prod(A, B)). λx:A. " +
				"    extended_to_real(ν(«section»(E, x)))"},
			{Name: "rectangles", Text: "λS:set(set(A)). λT:set(set(B)). " +
				"    {set_cross(s, t):set(prod(A, B)) | s:set(A), t:set(B) | s ∈ S ∧ t ∈ T}"},
			{Name: "partial", Text: "λf:(num → A → real). λn:num. λx:A. Σ_{i∈0 .. n} f(i, x)"},
		},
	}, func(ctx *Script, headline string) *GoalStackNode {
		measurablePartialSums := ctx.Lemma(Statement{
			Binders:    "∀Ω:set(A). ∀S:set(set(A)). ∀f:(num → A → real).",
			Hypotheses: []string{"sigma_algebra_on(Ω, S)", "∀n:num. real_measurable(Ω, S, f(n))"},
			Conclusion: "∀n:num. real_measurable(Ω, S, «partial»(f, n))",
		}, func(
			a *Argument,
			Ω *Expr[Set[A]],
			S *Expr[Set[Set[A]]],
			f *Arrow[Nat, Fun[A, Real]],
			sigma, terms Fact,
		) {
			a.FixAs[Nat]("n")
			below := a.Have(
				"an index is below n + 1 exactly when it is at most n",
				"∀j:num. j < n + 1 ⇔ j ≤ n",
				ByArith())
			segment := a.Have(
				"the segment from zero to n is the set of indices below n + 1",
				"0 .. n = {j:num | j < n + 1}",
				BySets(below, num_segment.MembershipFromZero))
			a.Show(
				"a finite sum of measurable functions is measurable",
				Simp(Fwd(segment)),
				By(sigma, terms, measurable_function.RealMeasurableSum.At(Ω, S, f, a.TermAs[Nat]("n + 1"))))
		})
		finiteSections := ctx.Lemma(Statement{
			Binders: "∀Ω:set(A). " +
				"∀S:set(set(A)). " +
				"∀V:set(B). " +
				"∀T:set(set(B)). " +
				"∀ν:(set(B) → extended_nonneg_real). " +
				"∀E:set(prod(A, B)).",
			Hypotheses: []string{
				"sigma_algebra_on(Ω, S)", "measure_on(V, T, ν)", "ν(V) ≠ extended_infinity",
				"E ∈ product_sigma(Ω, S, V, T)",
			},
			Conclusion: "extended_measurable(Ω, S, λx:A. ν(«section»(E, x)))",
		}, func(a *Argument, Ω *Expr[Set[A]], S *Expr[Set[Set[A]]], V *Expr[Set[B]], T *Expr[Set[Set[B]]],
			ν *Arrow[Set[B], ExtendedNonnegReal], E *Expr[Set[Prod[A, B]]], sigmaS, measure, finite, inE Fact) {
			laws := a.Conjuncts(
				a.Unfolded(measure, measure_space.MeasureOn),
				"the second factor has a σ-algebra",
				"ν gives the empty set mass zero",
				"ν is countably additive")
			sigmaT, zero, countable := laws[0], laws[1], laws[2]
			K, kDef := a.LetAs[Set[Prod[A, B]]]("K", "set_cross(Ω, V)")
			P, pDef := a.LetAs[Set[Set[Prod[A, B]]]]("P", "product_sigma(Ω, S, V, T)")
			C, cDef := a.LetAs[Set[Set[Prod[A, B]]]]("C", "«rectangles»(S, T)")
			projections := measurable_space.ProductSigmaProjections.At(Ω, S, V, T)
			rectanglesIn := a.Have(
				"the measurable rectangles are product events",
				"C ⊆ P",
				BySets(sigmaS, sigmaT, pDef, cDef, projections))
			product := a.Have(
				"the product σ-algebra contains the generating π-system",
				"sigma_algebra_on(K, P) ∧ pi_system_on(K, C) ∧ C ⊆ P",
				By(
					sigmaS,
					sigmaT,
					kDef,
					pDef,
					cDef,
					rectanglesIn,
					projections,
					measurable_space.ProductSigmaPiSystem.At(Ω, S, V, T)))
			sections := a.Have(
				"each section of a product event belongs to T",
				"∀R:set(prod(A, B)). ∀x:A. R ∈ P ⇒ «section»(R, x) ∈ T",
				Derive(func(b *Argument) {
					R := b.FixAs[Set[Prod[A, B]]]("R")
					x := b.FixAs[A]("x")
					event := b.Assume()
					b.Show(
						"the section of a product event is measurable",
						By(
							sigmaS,
							sigmaT,
							pDef,
							event,
							sigma_algebra.SigmaAlgebraOnDef.At(Ω, S),
							ProductSectionMeasurable.At(Ω, S, V, T, R, x)))
				}))
			insideT := a.Have(
				"measurable second-factor sets lie in the carrier",
				"T ⊆ {t:set(B) | t ⊆ V}",
				By(sigmaT, sigma_algebra.SigmaAlgebraOnDef.At(V, T)))
			finiteT := a.Have(
				"every measurable second-factor set has finite mass",
				"∀t:set(B). t ∈ T ⇒ ν(t) ≠ extended_infinity",
				Derive(func(b *Argument) {
					t := b.FixAs[Set[B]]("t")
					inT := b.Assume()
					sub := b.Have(
						"t lies in the carrier",
						"t ⊆ V",
						BySets(insideT, inT))
					b.Show(
						"its mass is bounded by the finite mass of the carrier",
						By(
							measure,
							sigmaT,
							inT,
							sub,
							finite,
							sigma_algebra.SigmaAlgebraOnDef.At(V, T),
							measure_space.MeasureMono.At(V, T, ν, t, V),
							extended_nonneg_real.ExtendedLeDef.At(ν.Apply(t), ν.Apply(V))))
				}))
			D, dDef := a.LetAs[Set[Set[Prod[A, B]]]]("D",
				"{R:set(prod(A, B)) | R ∈ P ∧ real_measurable(Ω, S, «realSectionMass»(ν, R))}")
			members := a.Have(
				"D consists of the product events with measurable real section masses",
				"∀R:set(prod(A, B)). R ∈ D ⇔ R ∈ P ∧ real_measurable(Ω, S, «realSectionMass»(ν, R))",
				BySets(dDef))
			cross := set_product.InCross.Inst(TypeBinder.BindA[A](), TypeBinder.BindB[B]())
			rectangleValues := a.Have(
				"the real section mass of each measurable rectangle is measurable",
				Statement{
					Binders:    "∀s:set(A). ∀t:set(B).",
					Hypotheses: []string{"s ∈ S", "t ∈ T"},
					Conclusion: "real_measurable(Ω, S, «realSectionMass»(ν, set_cross(s, t)))",
				},
				Derive(func(b *Argument) {
					s := b.FixAs[Set[A]]("s")
					b.FixAs[Set[B]]("t")
					factors := b.Assume()
					rectangleSections := b.Have(
						"the section is t on s and empty elsewhere",
						"∀x:A. «section»(set_cross(s, t), x) = COND(x ∈ s, t, ∅)",
						BySets(cross))
					values := b.Have(
						"the section value is the indicator of s at height ν(t) read as a real",
						"«realSectionMass»(ν, set_cross(s, t)) = (λx:A. COND(x ∈ s, extended_to_real(ν(t)), &0))",
						By(rectangleSections, zero, extended_nonneg_real.ToRealZero))
					b.Show(
						"the indicator of the measurable first factor is measurable",
						By(
							sigmaS,
							factors,
							values,
							measurable_function.RealMeasurableIndicator.At(Ω, S, s, b.TermAs[Real]("extended_to_real(ν(t))"))))
				}))
			generators := a.Have(
				"the generating rectangles belong to D",
				"C ⊆ D",
				Simp(Fwd(set_basic.SubsetDef.Inst[Set[Prod[A, B]]]())),
				Derive(func(b *Argument) {
					R := b.FixAs[Set[Prod[A, B]]]("R")
					member := b.Assume()
					inP := b.Have(
						"each generator is a product event",
						"R ∈ P",
						BySets(member, product))
					s, t, factors := b.Unpack2As[Set[A], Set[B]](b.Simplified(member, Fwd(cDef)), "s", "t")
					b.Show(
						"the two factors give a measurable section mass",
						By(Normalized, inP, factors, members.At(R), rectangleValues.At(s, t)))
				}))
			within := a.Have(
				"each member of D is a product event within the product carrier",
				"D ⊆ {R:set(prod(A, B)) | R ⊆ K}",
				BySets(dDef, product, sigma_algebra.SigmaAlgebraOnDef.At(K, P)))
			carrierInD := a.Have(
				"the carrier belongs to D as the product of the two carriers",
				"K ∈ D",
				Derive(func(b *Argument) {
					rect := b.Have(
						"the product carrier is a generating rectangle",
						"K ∈ C",
						Simp(Fwd(kDef), Fwd(cDef)),
						By(
							sigmaS,
							sigmaT,
							sigma_algebra.SigmaAlgebraOnDef.At(Ω, S),
							sigma_algebra.SigmaAlgebraOnDef.At(V, T)))
					b.Show(
						"the generators are included in D",
						BySets(rect, generators))
				}))
			complements := a.Have(
				"relative complements stay in D",
				"∀R:set(prod(A, B)). R ∈ D ⇒ K ∖ R ∈ D",
				Derive(func(b *Argument) {
					R := b.FixAs[Set[Prod[A, B]]]("R")
					inD := b.Assume()
					complement := b.TermAs[Set[Prod[A, B]]]("K ∖ R")
					properties := b.Have(
						"both events are in the product σ-algebra and the original section value is measurable",
						"R ∈ P ∧ K ∖ R ∈ P ∧ real_measurable(Ω, S, «realSectionMass»(ν, R))",
						By(inD, members.At(R), product, sigma_algebra.SigmaAlgebraOnDef.At(K, P)))
					sectionComplement := b.Have(
						"at a point of Ω the section of the complement is the relative complement in V",
						"∀x:A. x ∈ Ω ⇒ «section»(K ∖ R, x) = V ∖ «section»(R, x)",
						BySets(kDef, cross))
					subtract := b.Have(
						"the complement's real section mass is ν(V) − f, written ν(V) + -f "+
							"so that measurability passes through a constant, a negation and a sum",
						Statement{
							Binders:    "∀x:A.",
							Hypotheses: []string{"x ∈ Ω"},
							Conclusion: "extended_to_real(ν(V)) + -«realSectionMass»(ν, R, x) = «realSectionMass»(ν, K ∖ R, x)",
						},
						Derive(func(c *Argument) {
							x := c.FixAs[A]("x")
							inΩ := c.Assume()
							U := c.TermAs[Set[B]]("«section»(R, x)")
							W := c.TermAs[Set[B]]("«section»(K ∖ R, x)")
							events := c.Have(
								"the two sections are measurable",
								"«section»(R, x) ∈ T ∧ «section»(K ∖ R, x) ∈ T",
								By(properties, sections.At(R, x), sections.At(complement, x)))
							inside := c.Have(
								"the original section lies in V",
								"«section»(R, x) ⊆ V",
								BySets(insideT, events))
							split := c.Have(
								"the two section masses add to the carrier mass",
								"ν(V) = ν(«section»(R, x)) + ν(«section»(K ∖ R, x))",
								By(
									measure,
									sigmaT,
									events,
									inside,
									inΩ,
									sectionComplement.At(x),
									sigma_algebra.SigmaAlgebraOnDef.At(V, T),
									measure_space.MeasureAddDiff.At(V, T, ν, U, V)))
							c.Show(
								"read both finite masses as reals and subtract",
								ByArith(
									split,
									events,
									finiteT.At(U),
									finiteT.At(W),
									extended_nonneg_real.ToRealAdd.At(ν.Apply(U), ν.Apply(W))))
						}))
					difference := b.TermAs[Fun[A, Real]]("λx:A. extended_to_real(ν(V)) + -«realSectionMass»(ν, R, x)")
					complementValue := b.TermAs[Fun[A, Real]]("«realSectionMass»(ν, K ∖ R)")
					linear := b.Have(
						"ν(V) + -f is measurable, a constant plus the negation of a measurable function",
						"real_measurable(Ω, S, λx:A. extended_to_real(ν(V)) + -«realSectionMass»(ν, R, x))",
						By(
							sigmaS,
							properties,
							measurable_function.RealMeasurableConst.At(Ω, S, b.TermAs[Real]("extended_to_real(ν(V))")),
							measurable_function.RealMeasurableNeg.At(Ω, S, b.TermAs[Fun[A, Real]]("«realSectionMass»(ν, R)")),
							measurable_function.RealMeasurableAdd.At(Ω, S,
								b.TermAs[Fun[A, Real]]("λx:A. extended_to_real(ν(V))"),
								b.TermAs[Fun[A, Real]]("λx:A. -«realSectionMass»(ν, R, x)"))))
					measurable := b.Have(
						"agreement on Ω makes the complement's section value measurable",
						"real_measurable(Ω, S, «realSectionMass»(ν, K ∖ R))",
						By(
							linear,
							subtract,
							measurable_function.RealMeasurableDef.At(Ω, S, difference),
							measurable_function.RealMeasurableDef.At(Ω, S, complementValue),
							measurable_space.MeasurableCongruence.At(Ω, S, b.TermAs[Set[Real]]("𝕌"),
								b.TermAs[Set[Set[Real]]]("borel_sets(real_topology)"), difference, complementValue)))
					b.Show(
						"the complement satisfies both conditions for membership in D",
						By(properties, measurable, members.At(complement)))
				}))
			disjointUnions := a.Have(
				"countable disjoint unions stay in D",
				Statement{
					Binders:    "∀p:(num → set(prod(A, B))).",
					Hypotheses: []string{"∀n:num. p(n) ∈ D", "∀i j:num. i ≠ j ⇒ p(i) ∩ p(j) = ∅"},
					Conclusion: "⋃image(p, 𝕌) ∈ D",
				},
				Derive(func(b *Argument) {
					b.FixAs[Fun[Nat, Set[Prod[A, B]]]]("p")
					given := b.Conjuncts(
						b.Assume(),
						"all terms are in D",
						"the terms are pairwise disjoint")
					terms, disjoint := given[0], given[1]
					U := b.TermAs[Set[Prod[A, B]]]("⋃image(p, 𝕌)")
					properties := b.Have(
						"each term is a product event with measurable section value",
						"(∀n:num. p(n) ∈ P) ∧ (∀n:num. real_measurable(Ω, S, «realSectionMass»(ν, p(n))))",
						By(terms, members))
					union := b.Have(
						"the union belongs to the product σ-algebra",
						"⋃image(p, 𝕌) ∈ P",
						By(product, properties, sigma_algebra.SigmaAlgebraOnDef.At(K, P)))
					converges := b.Have(
						"at each point the partial sums converge to the union's section value",
						Statement{
							Binders:    "∀x:A.",
							Hypotheses: []string{"x ∈ Ω"},
							Conclusion: "(λn:num. «partial»(λi:num. «realSectionMass»(ν, p(i)), n, x)) ⟶ " +
								"«realSectionMass»(ν, ⋃image(p, 𝕌), x)",
						},
						Derive(func(c *Argument) {
							x := c.FixAs[A]("x")
							c.Assume()
							trace := c.TermAs[Fun[Nat, Set[B]]]("λn:num. «section»(p(n), x)")
							traceUnion := c.TermAs[Set[B]]("«section»(⋃image(p, 𝕌), x)")
							values := c.TermAs[Fun[Nat, Real]]("λn:num. «realSectionMass»(ν, p(n), x)")
							unionValue := c.TermAs[Real]("«realSectionMass»(ν, ⋃image(p, 𝕌), x)")
							traces := c.Have(
								"the sections of the sequence are measurable",
								"∀n:num. «section»(p(n), x) ∈ T",
								Derive(func(d *Argument) {
									d.FixAs[Nat]("n")
									d.Show(
										"each original term is a product event",
										By(properties, sections.At(d.TermAs[Set[Prod[A, B]]]("p(n)"), x)))
								}))
							disjointTraces := c.Have(
								"disjointness passes to the sections",
								"∀i j:num. i ≠ j ⇒ «section»(p(i), x) ∩ «section»(p(j), x) = ∅",
								BySets(disjoint))
							distribute := c.Have(
								"the section of the union is the union of the sections",
								"«section»(⋃image(p, 𝕌), x) = ⋃image(λn:num. «section»(p(n), x), 𝕌)",
								BySets())
							additivity := c.Have(
								"the section mass of the union is the series of the section masses",
								"ν(«section»(⋃image(p, 𝕌), x)) = extended_series(λn:num. ν(«section»(p(n), x)))",
								By(countable.At(trace), traces, disjointTraces, distribute))
							finiteTotal := c.Have(
								"the section of the union has finite mass",
								"ν(«section»(⋃image(p, 𝕌), x)) ≠ extended_infinity",
								By(union, sections.At(U, x), finiteT.At(traceUnion)))
							embedding := c.Have(
								"embedding each real value recovers its finite section mass",
								"(λn:num. extended_of_real(«realSectionMass»(ν, p(n), x))) = (λn:num. ν(«section»(p(n), x)))",
								Funext(),
								Derive(func(d *Argument) {
									n := d.FixAs[Nat]("n")
									section := d.TermAs[Set[B]]("«section»(p(n), x)")
									d.Show(
										"the nth section is measurable and finite",
										By(traces.At(n), finiteT.At(section), extended_nonneg_real.OfRealToReal.At(ν.Apply(section))))
								}))
							series := c.Have(
								"the series of embedded real values has the same total",
								"extended_series(λn:num. extended_of_real(«realSectionMass»(ν, p(n), x))) = "+
									"ν(«section»(⋃image(p, 𝕌), x))",
								By(embedding, additivity))
							sums := c.Have(
								"the real series of nonnegative values sums to the finite total",
								"real_sums(λn:num. «realSectionMass»(ν, p(n), x), «realSectionMass»(ν, ⋃image(p, 𝕌), x))",
								By(
									series,
									finiteTotal,
									extended_nonneg_real.ToRealNonneg,
									extended_nonneg_real.SeriesFinite.At(values)))
							c.Show(
								"real summation means convergence of the partial sums",
								By(sums, real_series.RealSumsDef.At(values, unionValue)))
						}))
					realTerms := b.TermAs[Fun[Nat, Fun[A, Real]]]("λn:num. «realSectionMass»(ν, p(n))")
					partialSums := b.TermAs[Fun[Nat, Fun[A, Real]]](
						"λn:num. λx:A. Σ_{i∈0 .. n} «realSectionMass»(ν, p(i), x)")
					unionValue := b.TermAs[Fun[A, Real]]("«realSectionMass»(ν, ⋃image(p, 𝕌))")
					measurable := b.Have(
						"the pointwise limit of the measurable partial sums is measurable",
						"real_measurable(Ω, S, «realSectionMass»(ν, ⋃image(p, 𝕌)))",
						By(
							sigmaS,
							properties,
							converges,
							At(measurablePartialSums, Ω, S, realTerms),
							measurable_function.RealMeasurableLimit.At(Ω, S, partialSums, unionValue)))
					b.Show(
						"the union satisfies both conditions for membership in D",
						By(union, measurable, members.At(U)))
				}))
			lambda := a.Have(
				"D satisfies the λ-system laws",
				"lambda_system_on(K, D)",
				By(within, carrierInD, complements, disjointUnions, sigma_algebra.LambdaSystemDef.At(K, D)))
			generated := a.Have(
				"the measurable rectangles generate P",
				"generated_sigma(K, C) = P",
				By(pDef, kDef, cDef, measurable_space.ProductSigmaDef.At(Ω, S, V, T)))
			event := a.Have(
				"the π–λ theorem puts every product event in D",
				"E ∈ D",
				BySets(inE, generators, lambda, product, generated, sigma_algebra.PiLambda.At(K, C, D)))
			embedding := a.Have(
				"embedding the real section value recovers the extended mass pointwise",
				"(λx:A. extended_of_real(«realSectionMass»(ν, E, x))) = (λx:A. ν(«section»(E, x)))",
				Funext(),
				Derive(func(b *Argument) {
					x := b.FixAs[A]("x")
					section := b.TermAs[Set[B]]("«section»(E, x)")
					b.Show(
						"each measurable section has finite mass",
						By(
							inE,
							sections.At(E, x),
							finiteT.At(section),
							extended_nonneg_real.OfRealToReal.At(ν.Apply(section))))
				}))
			a.Show(
				"the extended embedding preserves measurability",
				By(
					sigmaS,
					event,
					members.At(E),
					embedding,
					measurable_function.ExtendedMeasurableOfReal.At(
						Ω, S, a.TermAs[Fun[A, Real]]("«realSectionMass»(ν, E)"))))
		})
		return ctx.Theorem(headline, func(
			a *Argument,
			Ω *Expr[Set[A]],
			S *Expr[Set[Set[A]]],
			V *Expr[Set[B]],
			T *Expr[Set[Set[B]]],
			ν *Arrow[Set[B], ExtendedNonnegReal],
			E *Expr[Set[Prod[A, B]]],
			sigmaS, sigmaFinite, event Fact,
		) {
			measure := a.Have(
				"ν is a measure on the second factor",
				"measure_on(V, T, ν)",
				By(sigmaFinite, measure_space.SigmaFiniteDef.At(V, T, ν)))
			_, cover := a.ObtainAs[Fun[Nat, Set[B]]](
				"σ-finiteness supplies an increasing cover of V by measurable sets of finite mass",
				"∃q:(num → set(B)). "+
					"    (∀n:num. q(n) ∈ T ∧ ν(q(n)) ≠ extended_infinity) ∧ "+
					"    (∀n:num. q(n) ⊆ q(n + 1)) ∧ "+
					"    ⋃image(q, 𝕌) = V",
				By(sigmaFinite, measure_space.SigmaFiniteIncreasingCover.At(V, T, ν)))
			covered := a.Conjuncts(
				cover,
				"the cover has measurable sets of finite mass",
				"the cover increases",
				"the cover fills V")
			sets, increasing, exhausts := covered[0], covered[1], covered[2]
			base := a.Have(
				"the second factor has a σ-algebra",
				"sigma_algebra_on(V, T)",
				By(measure, measure_space.MeasureOn.At(V, T, ν)))
			measurable := a.Have(
				"every finite restriction gives a measurable section-mass function",
				"∀n:num. extended_measurable(Ω, S, λx:A. restricted_measure(ν, q(n), «section»(E, x)))",
				Derive(func(b *Argument) {
					n := b.FixAs[Nat]("n")
					piece := b.TermAs[Set[B]]("q(n)")
					cut := b.TermAs[Fun[Set[B], ExtendedNonnegReal]]("restricted_measure(ν, q(n))")
					within := b.Have(
						"the cover set lies in the carrier the cover exhausts",
						"V ∩ q(n) = q(n)",
						BySets(exhausts))
					b.Show(
						"the restricted measure has finite carrier mass, so the finite case applies",
						By(
							sigmaS,
							measure,
							event,
							sets.At(n),
							within,
							measure_space.RestrictMeasureOnCarrier.At(V, T, ν, piece),
							measure_space.RestrictMeasureDef.At(ν, piece, V),
							At(finiteSections, Ω, S, V, T, cut, E)))
				}))
			fullMass := a.Have(
				"continuity from below writes the full section mass as a pointwise supremum",
				"(λx:A. extended_sup(image(λn:num. restricted_measure(ν, q(n), «section»(E, x)), 𝕌))) = "+
					"(λx:A. ν(«section»(E, x)))",
				Funext(),
				Derive(func(b *Argument) {
					x := b.FixAs[A]("x")
					cuts := b.TermAs[Fun[Nat, Set[B]]]("λn:num. «section»(E, x) ∩ q(n)")
					section := b.Have(
						"the section belongs to T",
						"«section»(E, x) ∈ T",
						By(
							event,
							sigmaS,
							base,
							sigma_algebra.SigmaAlgebraOnDef.At(Ω, S),
							ProductSectionMeasurable.At(Ω, S, V, T, E, x)))
					cutEvents := b.Have(
						"each section cut is a measurable intersection",
						"∀n:num. «section»(E, x) ∩ q(n) ∈ T",
						Derive(func(c *Argument) {
							n := c.FixAs[Nat]("n")
							c.Show(
								"both factors are measurable",
								By(section, base, sets.At(n), sigma_algebra.SigmaFiniteOperations.At(V, T)))
						}))
					cutIncreasing := b.Have(
						"the section cuts increase with the cover",
						"∀n:num. («section»(E, x) ∩ q(n)) ⊆ («section»(E, x) ∩ q(n + 1))",
						BySets(increasing))
					allInside := b.Have(
						"each measurable second-factor set lies in V",
						"T ⊆ {t:set(B) | t ⊆ V}",
						By(base, sigma_algebra.SigmaAlgebraOnDef.At(V, T)))
					contained := b.Have(
						"the section lies within V",
						"«section»(E, x) ⊆ V",
						BySets(section, allInside))
					union := b.Have(
						"the cuts exhaust the whole section",
						"⋃image(λn:num. «section»(E, x) ∩ q(n), 𝕌) = «section»(E, x)",
						BySets(exhausts, contained))
					b.Show(
						"the original measure of the section is the supremum of the restricted masses",
						Simp(Fwd(measure_space.RestrictMeasureDef)),
						By(
							measure,
							cutEvents,
							cutIncreasing,
							union,
							measure_space.MeasureContinuousIncreasing.At(V, T, ν, cuts)))
				}))
			a.Show(
				"the pointwise supremum of the restricted section masses is measurable",
				By(
					sigmaS,
					measurable,
					fullMass,
					measurable_function.ExtendedMeasurableSup.At(Ω, S,
						a.TermAs[Fun[Nat, Fun[A, ExtendedNonnegReal]]](
							"λn:num. λx:A. restricted_measure(ν, q(n), «section»(E, x))"))))
		})
	}),
})}
